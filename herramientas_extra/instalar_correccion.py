"""Prepara, instala y deshace la copia corregida de un juego con XUnity (Unity + BepInEx).

El archivo de traducciones del juego (``BepInEx/Translation/<idioma>/Text/_AutoGeneratedTranslations.txt``)
nunca se corrige directamente: se trabaja sobre una copia en ``workspace/<juego>/correccion_xunity/``.

1. ``preparar``: copia el archivo del juego (la copia de trabajo) y guarda una foto del original
   (``_AutoGeneratedTranslations.original.txt``). Después ``8_auditar_genero.py --xunity <copia> --corregir``
   corrige SOLO la copia.
2. ``instalar``: con el juego cerrado y su archivo igual que la foto (nadie lo ha cambiado desde entonces:
   si el juego ha guardado frases nuevas, instalar las borraría), pone la copia corregida en el juego y
   comprueba que ha quedado idéntica.
3. ``deshacer``: con el juego cerrado y su archivo igual que la copia corregida, vuelve a poner la foto.

Uso: python herramientas_extra/instalar_correccion.py --ruta "D:\\Juegos\\Mi juego" preparar|instalar|deshacer|estado
"""
from __future__ import annotations

import argparse
import hashlib
import os
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

RAIZ = Path(__file__).resolve().parent.parent
if str(RAIZ) not in sys.path:
    sys.path.insert(0, str(RAIZ))

from traductor import config  # noqa: E402

NOMBRE = "_AutoGeneratedTranslations.txt"
CARPETA = "correccion_xunity"
FOTO = "_AutoGeneratedTranslations.original.txt"


class ErrorInstalacion(Exception):
    """No se puede instalar/deshacer ahora; el mensaje explica por qué en lenguaje sencillo."""


def _hash(ruta: Path) -> str:
    return hashlib.sha256(ruta.read_bytes()).hexdigest()


def archivo_del_juego(ruta_juego: Path) -> Path | None:
    """El ``_AutoGeneratedTranslations.txt`` del juego (BepInEx/Translation/<idioma>/Text/)."""
    for base in (ruta_juego / "BepInEx" / "Translation", ruta_juego / "Translation", ruta_juego / "AutoTranslator"):
        if base.is_dir():
            encontrados = sorted(base.glob(f"*/Text/{NOMBRE}"))
            if encontrados:
                return encontrados[0]
    return None


def carpeta_correccion(juego: str) -> Path:
    return config.carpeta_juego(juego) / CARPETA


def procesos_del_juego(ruta_juego: Path) -> list[str]:
    """Nombres de los programas abiertos que están dentro de la carpeta del juego."""
    try:
        import psutil
    except ImportError:  # sin psutil no se puede comprobar: mejor no instalar
        return ["(no se puede comprobar: falta psutil)"]
    base = os.path.normcase(str(ruta_juego.resolve()))
    abiertos = []
    for p in psutil.process_iter(["exe", "name"]):
        exe = p.info.get("exe")
        if exe and os.path.normcase(exe).startswith(base + os.sep):
            abiertos.append(p.info.get("name") or Path(exe).name)
    return sorted(set(abiertos))


@dataclass
class Estado:
    archivo_juego: Path | None
    copia: Path
    foto: Path
    hay_copia: bool
    instalada: bool
    original_puesto: bool

    def texto(self) -> str:
        if self.archivo_juego is None:
            return "Este juego no tiene archivo de traducciones de XUnity."
        if not self.hay_copia:
            return "No hay copia corregida preparada."
        if self.instalada:
            return "La copia corregida está instalada en el juego."
        if self.original_puesto:
            return "Hay una copia corregida lista para instalar."
        return "El archivo del juego ha cambiado desde que se preparó la copia: vuelve a prepararla."


def estado(ruta_juego: Path, juego: str) -> Estado:
    archivo = archivo_del_juego(ruta_juego)
    carpeta = carpeta_correccion(juego)
    copia, foto = carpeta / NOMBRE, carpeta / FOTO
    hay = copia.exists() and foto.exists()
    h = _hash(archivo) if (archivo is not None and archivo.exists()) else None
    return Estado(archivo, copia, foto, hay,
                  instalada=bool(hay and h is not None and h == _hash(copia) and h != _hash(foto)),
                  original_puesto=bool(hay and h is not None and h == _hash(foto)))


def _copiar_seguro(origen: Path, destino: Path) -> None:
    tmp = destino.with_name(destino.name + ".instalando.tmp")
    shutil.copy2(origen, tmp)
    os.replace(tmp, destino)
    if _hash(destino) != _hash(origen):
        raise ErrorInstalacion(f"La copia en {destino} no ha quedado idéntica. Vuelve a intentarlo.")


def _juego_cerrado(ruta_juego: Path) -> None:
    abiertos = procesos_del_juego(ruta_juego)
    if abiertos:
        raise ErrorInstalacion(f"Cierra el juego primero (está abierto: {', '.join(abiertos)}).")


def preparar(ruta_juego: Path, juego: str) -> Path:
    """Copia el archivo del juego a workspace/<juego>/correccion_xunity/ (copia de trabajo + foto del original)."""
    archivo = archivo_del_juego(ruta_juego)
    if archivo is None:
        raise ErrorInstalacion("Este juego no tiene archivo de traducciones de XUnity (_AutoGeneratedTranslations.txt).")
    carpeta = carpeta_correccion(juego)
    carpeta.mkdir(parents=True, exist_ok=True)
    e = estado(ruta_juego, juego)
    if e.instalada:
        raise ErrorInstalacion("La copia corregida ya está instalada. Si quieres empezar otra, deshaz antes la instalación.")
    shutil.copy2(archivo, carpeta / FOTO)
    shutil.copy2(archivo, carpeta / NOMBRE)
    return carpeta / NOMBRE


def instalar(ruta_juego: Path, juego: str) -> str:
    e = estado(ruta_juego, juego)
    if e.archivo_juego is None:
        raise ErrorInstalacion("Este juego no tiene archivo de traducciones de XUnity.")
    if not e.hay_copia:
        raise ErrorInstalacion("No hay copia corregida. Prepárala primero.")
    if e.instalada:
        return "La copia corregida ya estaba instalada: no se ha cambiado nada."
    if not e.original_puesto:
        raise ErrorInstalacion("El archivo del juego ha cambiado desde que se preparó la copia (el juego ha guardado "
                               "frases nuevas). Instalar ahora las borraría: vuelve a preparar la copia.")
    if _hash(e.copia) == _hash(e.foto):
        return "La copia no tiene ninguna corrección: no hace falta instalar nada."
    _juego_cerrado(ruta_juego)
    _copiar_seguro(e.copia, e.archivo_juego)
    return (f"Instalada la copia corregida en {e.archivo_juego}. El original está guardado en {e.foto} "
            "(botón «Deshacer» para volver a ponerlo).")


def deshacer(ruta_juego: Path, juego: str) -> str:
    e = estado(ruta_juego, juego)
    if e.archivo_juego is None or not e.foto.exists():
        raise ErrorInstalacion("No hay nada que deshacer.")
    if e.original_puesto:
        return "El juego ya tiene el archivo original: no se ha cambiado nada."
    if not e.instalada:
        raise ErrorInstalacion("El archivo del juego ha cambiado desde que se instaló la copia (frases nuevas). "
                               "Deshacer ahora las borraría, así que no se toca.")
    _juego_cerrado(ruta_juego)
    _copiar_seguro(e.foto, e.archivo_juego)
    return f"Vuelto a poner el archivo original en {e.archivo_juego}."


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--ruta", required=True, help="Carpeta del juego")
    ap.add_argument("--juego", help="Perfil en workspace/<juego>/ (por defecto se deduce de la carpeta)")
    ap.add_argument("accion", choices=["estado", "preparar", "instalar", "deshacer"])
    args = ap.parse_args(argv)
    ruta = Path(args.ruta)
    juego = config.resolver_juego(args.juego, ruta)
    try:
        if args.accion == "estado":
            print(estado(ruta, juego).texto())
        elif args.accion == "preparar":
            copia = preparar(ruta, juego)
            print(f"Copia preparada: {copia}\nCorrígela con: python 8_auditar_genero.py --ruta \"{ruta}\" "
                  f"--xunity \"{copia}\" --corregir")
        elif args.accion == "instalar":
            print(instalar(ruta, juego))
        else:
            print(deshacer(ruta, juego))
    except ErrorInstalacion as e:
        print(f"No se ha hecho nada: {e}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
