"""Resumen del registro del proxy de Unity: qué pidió XUnity al jugar, quién lo respondió y por qué no estaba.

XUnity solo llama al proxy cuando NO encuentra la frase en su archivo de traducciones. Para cada frase que
acabó en la caché o en el modelo se busca algo parecido en ese archivo, para saber por qué no coincidió:

- ``espacios``: la misma frase con otros espacios o saltos de línea.
- ``mayusculas``: la misma frase con otras mayúsculas.
- ``etiquetas``: la misma frase sin etiquetas (``<color>``, ``<b>``…).
- ``cifras``: la misma frase con otros números.
- ``trozo``: es un trozo de una frase que sí está (el juego la enseña por partes).
- ``nueva``: nada parecido en el archivo.

Uso:
    python herramientas_extra/analizar_registro_proxy.py --juego <perfil> [--fecha AAAA-MM-DD] [--archivo <txt>]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

RAIZ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(RAIZ))

from traductor import config, xunity  # noqa: E402

_ETIQUETA = re.compile(r"<[^<>]*>|\{/?(?:color|i|b|u|s|size)(?:=[^{}]*)?\}")
_CIFRAS = re.compile(r"\d+(?:[.,]\d+)?")


def _espacios(t: str) -> str:
    return re.sub(r"\s+", " ", t).strip()


def leer_registro(rutas: list[Path]) -> list[dict]:
    filas = []
    for ruta in rutas:
        for linea in ruta.read_text(encoding="utf-8").splitlines():
            try:
                filas.append(json.loads(linea))
            except json.JSONDecodeError:
                continue
    return filas


class Buscador:
    """Índices del archivo de XUnity para buscar frases parecidas."""

    def __init__(self, traducciones: dict[str, str]):
        self.claves = list(traducciones)
        self.por = {
            "espacios": {_espacios(k): k for k in self.claves},
            "mayusculas": {_espacios(k).lower(): k for k in self.claves},
            "etiquetas": {_espacios(_ETIQUETA.sub("", k)).lower(): k for k in self.claves},
            "cifras": {_CIFRAS.sub("#", _espacios(_ETIQUETA.sub("", k)).lower()): k for k in self.claves},
        }
        self._largas = [_espacios(k) for k in self.claves if len(k) > 20]

    def motivo(self, texto: str) -> tuple[str, str | None]:
        """(motivo, clave parecida del archivo)."""
        e = _espacios(texto)
        pruebas = (("espacios", e), ("mayusculas", e.lower()),
                   ("etiquetas", _espacios(_ETIQUETA.sub("", texto)).lower()),
                   ("cifras", _CIFRAS.sub("#", _espacios(_ETIQUETA.sub("", texto)).lower())))
        for nombre, clave in pruebas:
            if clave and clave in self.por[nombre]:
                return nombre, self.por[nombre][clave]
        limpio = _espacios(_ETIQUETA.sub("", texto))
        if len(limpio) >= 8:
            for k in self._largas:
                if limpio in k:
                    return "trozo", k
        return "nueva", None


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--juego", required=True, help="perfil de workspace/")
    p.add_argument("--fecha", help="solo el registro de ese día (AAAA-MM-DD); por defecto, todos")
    p.add_argument("--archivo", help="_AutoGeneratedTranslations.txt del juego, para buscar por qué no coincidió")
    p.add_argument("--ejemplos", type=int, default=15, help="ejemplos por motivo")
    args = p.parse_args()

    carpeta = config.carpeta_juego(args.juego) / "registro_proxy"
    rutas = sorted(carpeta.glob(f"{args.fecha or '*'}.jsonl"))
    if not rutas:
        print(f"No hay registro en {carpeta}")
        return
    filas = leer_registro(rutas)
    vias = Counter(f.get("via", "?").split(":")[0].replace("oculto+", "") for f in filas)
    unicas = {f.get("texto", "") for f in filas}
    print(f"{len(filas)} peticiones ({len(unicas)} textos distintos) en {', '.join(r.name for r in rutas)}")
    for via, n in vias.most_common():
        print(f"  {via:12} {n:6}  ({n * 100 / len(filas):.0f} %)")

    directas = {}
    for f in filas:
        if f.get("via", "").replace("oculto+", "") in ("cache", "modelo") or f.get("via", "").startswith("fallo"):
            directas.setdefault(f.get("texto", ""), f)
    print(f"\n{len(directas)} textos distintos respondidos con la caché o el modelo (o que fallaron).")
    if not args.archivo:
        return
    buscador = Buscador(xunity.leer_traducciones(Path(args.archivo)))
    por_motivo: dict[str, list[tuple[str, str | None]]] = {}
    for texto in directas:
        motivo, parecida = buscador.motivo(texto)
        por_motivo.setdefault(motivo, []).append((texto, parecida))
    for motivo, lista in sorted(por_motivo.items(), key=lambda x: -len(x[1])):
        print(f"\n== {motivo}: {len(lista)}")
        for texto, parecida in lista[:args.ejemplos]:
            print(f"  {texto[:110]!r}")
            if parecida is not None:
                print(f"     ~ {parecida[:110]!r}")


if __name__ == "__main__":
    main()
