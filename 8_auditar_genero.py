CORREGIBLE = "corregible"
PROBABLE = "probable"
REVISAR = "revisar"

# Frases de antes y de después en las que se busca quién más está en la escena (posibles oyentes).
VENTANA_OYENTES = 3


@dataclass
class Hallazgo:
    """Una línea con un posible error de género."""

    archivo: str
    tipo: str            # 'corregible' (se aplica con --corregir), 'probable' (además --segunda) o 'revisar'
    hablante: str
    original: str
    traducido: str
    propuesta: str
    motivo: str
    contexto: str = ""   # frases (en inglés) de antes y de después, para revisar a mano


_MOTIVO_NOMBRE = "nombre protegido restaurado"


def _contexto(textos: list[str], i: int, ancho: int = 110) -> str:
    """'« anterior » ‖ « siguiente »' (originales en inglés) para el informe."""
    def corto(t: str) -> str:
        t = " ".join(t.split())
        return t if len(t) <= ancho else t[:ancho - 1] + "…"
    antes = f"« {corto(textos[i - 1])} »" if i > 0 else "(inicio)"
    despues = f"« {corto(textos[i + 1])} »" if i + 1 < len(textos) else "(fin)"
    return f"{antes} ‖ {despues}"


def _motivo(ctx) -> str:
    partes = []
    if ctx.hablante is not None:
        partes.append(("pensamiento de " if ctx.pensamiento else "habla ") + ctx.hablante.etiqueta())
    if ctx.destinatario is not None and ctx.destinatario_explicito:
        partes.append(f"se dirige a {ctx.destinatario.etiqueta()}")
    if ctx.mencionados:
        partes.append("menciona a " + ", ".join(p.etiqueta() for p in ctx.mencionados[:3]))
    return "; ".join(partes)


def hablantes_cerca(contextos: list[ContextoLinea], i: int, ventana: int = VENTANA_OYENTES) -> list[Personaje]:
    """Quienes hablan en las ``ventana`` frases de antes y de después de la ``i`` (sin repetir y sin
    contar los pensamientos): son los que están en la escena y pueden estar escuchando."""
    vistos: list[Personaje] = []
    for j in range(max(0, i - ventana), min(len(contextos), i + ventana + 1)):
        c = contextos[j]
        if j == i or c.hablante is None or c.pensamiento:
            continue
        if all(p.nombre != c.hablante.nombre for p in vistos):
            vistos.append(c.hablante)
    return vistos


def _forma_segunda(traducido: str) -> str | None:
    """Género con el que la traducción trata a quien escucha (None si no lo marca o marca los dos)."""
    marcas = marcas_genero(traducido)
    formas = [g for g, letra in ((HOMBRE, "m"), (MUJER, "f")) if f"2{letra}" in marcas]
    return formas[0] if len(formas) == 1 else None


def _segunda_sin_nombrar(ctx: ContextoLinea, original: str, traducido: str, oyentes: list[Personaje],
                         dudosas: bool, prota: Personaje | None = None) -> tuple[str, str, str] | None:
    """2.ª persona cuando la frase no nombra a quien escucha. Devuelve (tipo, propuesta, motivo) o None.

    Los posibles oyentes son el destinatario probable (el protagonista, si habla otro) y quienes hablan
    cerca. Ante la duda no se toca: si alguno es del género que usa la traducción, puede que la frase
    vaya para él/ella (solo sale con ``dudosas``); si el inglés ya dice el género ("girl", "Mom"), tampoco.
    Si habla alguien que no está en la ficha (un "NPC" genérico), se pasa ``prota`` como destinatario
    probable y quien habla no se descarta de los oyentes (podría ser cualquiera de ellos).
    """
    h = ctx.hablante
    if ctx.pensamiento or ctx.destinatario_explicito:
        return None
    d = ctx.destinatario if h is not None else prota
    if h is None and d is None:
        return None
    forma = _forma_segunda(traducido)
    if forma is None or forma in personas_con_genero_en(original):
        return None
    candidatos = [p for p in oyentes if h is None or p.nombre != h.nombre]
    if d is not None and (h is None or d.nombre != h.nombre) and all(p.nombre != d.nombre for p in candidatos):
        candidatos.insert(0, d)
    if not candidatos:
        return None
    quien = h.etiqueta() if h is not None else "alguien sin ficha"
    etiquetas = ", ".join(p.etiqueta() for p in candidatos[:5])
    forma_txt = "masculino" if forma == HOMBRE else "femenino"
    if any(p.genero == forma for p in candidatos):
        if dudosas and d is not None and es_genero_marcado(d.genero) and d.genero != forma:
            return (REVISAR, "", f"habla {quien} y no nombra a quien escucha: si es a {d.etiqueta()}, "
                                 f"la 2.ª persona no va en {forma_txt} (en la escena: {etiquetas})")
        return None
    generos = {p.genero for p in candidatos if es_genero_marcado(p.genero)}
    if len(generos) != 1:
        return None
    genero = generos.pop()
    propuesta = corregir_segunda_persona(traducido, genero)
    if propuesta == traducido or _forma_segunda(propuesta) == forma:
        propuesta = ""  # no se sabe corregir entera: a mano
    correcto = "masculino" if genero == HOMBRE else "femenino"
    motivo = (f"habla {quien} y no nombra a quien escucha; en la escena: {etiquetas}: "
              f"la 2.ª persona va en {correcto}")
    seguro = all(es_genero_marcado(p.genero) for p in candidatos)
    if not seguro:
        motivo += " (hay alguien de género desconocido)"
    return (PROBABLE if seguro and propuesta else REVISAR), propuesta, motivo


def _plural_en_escena(ctx: ContextoLinea, original: str, traducido: str,
                      oyentes: list[Personaje]) -> tuple[str, str, str] | None:
    """Plural de grupo ("nosotras", "¿estáis listos?") según quién está en la escena.

    El grupo de "nosotros" es quien habla más los de la escena; el de "vosotros", los de la escena menos
    quien habla. Solo es "probable" si son al menos dos, todos con género conocido e iguales, y la
    traducción usa el contrario. Si el inglés ya dice el género ("you girls"), no se toca.
    """
    h = ctx.hablante
    if h is None or ctx.pensamiento:
        return None
    marcas = marcas_plural(traducido)
    if not marcas:
        return None
    otros = [p for p in oyentes if p.nombre != h.nombre]
    d = ctx.destinatario
    if d is not None and d.nombre != h.nombre and all(p.nombre != d.nombre for p in otros):
        otros.insert(0, d)
    en_ingles = personas_con_genero_en(original)
    for persona, pronombre in (("1", "nosotros"), ("2", "vosotros")):
        formas = [g for g, letra in ((HOMBRE, "m"), (MUJER, "f")) if f"{persona}{letra}" in marcas]
        if len(formas) != 1 or formas[0] in en_ingles:
            continue
        forma = formas[0]
        grupo = ([h] if persona == "1" else []) + otros
        if len(grupo) < 2 or not all(es_genero_marcado(p.genero) for p in grupo):
            continue
        generos = {p.genero for p in grupo}
        if len(generos) != 1 or forma in generos:
            continue
        genero = generos.pop()
        propuesta = corregir_plural(traducido, genero, persona)
        if propuesta == traducido:
            continue
        correcto = "masculino" if genero == HOMBRE else "femenino"
        etiquetas = ", ".join(p.etiqueta() for p in grupo[:5])
        motivo = f"habla {h.etiqueta()}; '{pronombre}' en la escena: {etiquetas}: el plural va en {correcto}"
        if plural_a_medias(propuesta, genero, persona):
            return REVISAR, propuesta, motivo + " (la propuesta queda a medias: revísala)"
        if persona == "1" and not es_los_dos(original):
            # "We" puede incluir a gente que no está en la escena, o no incluir a quien escucha
            return REVISAR, propuesta, motivo + " (el 'nosotros' puede incluir a otros o dejar fuera a quien escucha)"
        return PROBABLE, propuesta, motivo
    return None


def _segunda_por_pista(ctx: ContextoLinea, traducido: str, genero_oyente: str) -> tuple[str, str, str] | None:
    """2.ª persona cuando otra traducción del juego (ruso/ucraniano: "ты готов"/"ты готова") dice el sexo de
    quien escucha. Es una pista fuerte, pero de otro traductor: "probable", no automático."""
    if ctx.pensamiento or genero_oyente not in (HOMBRE, MUJER):
        return None
    forma = _forma_segunda(traducido)
    if forma is None or forma == genero_oyente:
        return None
    propuesta = corregir_segunda_persona(traducido, genero_oyente)
    correcto = "masculino" if genero_oyente == HOMBRE else "femenino"
    motivo = f"la traducción rusa/ucraniana le habla a un{'' if genero_oyente == HOMBRE else 'a'} " \
             f"{'hombre' if genero_oyente == HOMBRE else 'mujer'}: la 2.ª persona va en {correcto}"
    if propuesta == traducido or _forma_segunda(propuesta) == forma:
        return REVISAR, "", motivo + " (no se sabe corregir entera)"
    return PROBABLE, propuesta, motivo


def revisar_par(ficha: FichaPersonajes, original: str, traducido: str, info: InfoLinea | None,
                archivo: str, dudosas: bool = False, ctx: ContextoLinea | None = None,
                oyentes: list[Personaje] | None = None, genero_oyente: str | None = None) -> Hallazgo | None:
    """Compara una línea original con su traducción. None si no hay nada que señalar.

    Con ``dudosas`` también señala (para revisar a mano, sin corregir) las líneas SIN hablante
    conocido cuya 1.ª persona tiene el género contrario al del protagonista: puede que las diga él/ella.
    ``ctx``: la línea ya resuelta (si no, se resuelve aquí). ``oyentes``: quienes hablan cerca
    (``hablantes_cerca``); sin ellos no se revisa la 2.ª persona que no nombra a quien escucha.
    ``genero_oyente``: sexo de quien escucha según otra traducción del juego (``PistasTablas``).
    """
    if not traducido or traducido == original:
        return None
    if ctx is None:
        ctx = resolver_linea(ficha, original, info)
    pista = _segunda_por_pista(ctx, traducido, genero_oyente) if genero_oyente else None
    nombre = ctx.hablante.nombre if ctx.hablante is not None else ""
    if pista is not None and (ctx.hablante is None or ctx.vacio):
        return Hallazgo(archivo, pista[0], nombre, original, traducido, pista[1], pista[2])
    if ctx.hablante is None and oyentes is not None:
        # Quien habla no está en la ficha ("NPC", "Clerk"...) o es un texto sin hablante: en 2.ª persona
        # casi siempre va para el protagonista, pero solo es "probable" si nadie más en la escena encaja.
        r = _segunda_sin_nombrar(ctx, original, traducido, oyentes, dudosas, ficha.protagonista())
        if r is not None:
            return Hallazgo(archivo, r[0], (info.hablante or info.codigo or "") if info else "",
                            original, traducido, r[1], r[2])
    if ctx.hablante is None and dudosas:
        prota = ficha.protagonista()
        if prota is not None and prota.genero_conocido:
            forma = "masculino" if prota.genero == "hombre" else "femenino"
            if contradice_genero(traducido, "1", prota.genero):
                return Hallazgo(archivo, REVISAR, "", original, traducido, "",
                                f"hablante desconocido: si lo dice {prota.etiqueta()}, la 1.ª persona va en {forma}")
            # Sin hablante ni destinatario (XUnity): casi todo lo que se dice en 2.ª persona va dirigido
            # al protagonista, pero no siempre (también habla él/ella con otros): solo para revisar.
            if ctx.destinatario is None and not ctx.pensamiento and contradice_genero(traducido, "2", prota.genero):
                return Hallazgo(archivo, REVISAR, "", original, traducido, "",
                                f"hablante desconocido: si se dirige a {prota.etiqueta()}, la 2.ª persona va en {forma}")
    if ctx.vacio:
        return None
    propuesta = aplicar_concordancia(traducido, original, ctx)
    if propuesta != traducido:
        return Hallazgo(archivo, CORREGIBLE, nombre, original, traducido, propuesta, _motivo(ctx))
    if pista is not None:
        return Hallazgo(archivo, pista[0], nombre, original, traducido, pista[1], pista[2])
    h = ctx.hablante
    if h is not None and h.genero_conocido and contradice_genero(traducido, "1", h.genero):
        return Hallazgo(archivo, REVISAR, nombre, original, traducido, "",
                        f"{_motivo(ctx)}: la 1.ª persona tiene el género contrario")
    d = ctx.destinatario
    if d is not None and ctx.destinatario_explicito and d.genero_conocido and contradice_genero(traducido, "2", d.genero):
        return Hallazgo(archivo, REVISAR, nombre, original, traducido, "",
                        f"{_motivo(ctx)}: la 2.ª persona tiene el género contrario")
    if oyentes is not None:
        r = (_segunda_sin_nombrar(ctx, original, traducido, oyentes, dudosas)
             or _plural_en_escena(ctx, original, traducido, oyentes))
        if r is not None:
            return Hallazgo(archivo, r[0], nombre, original, traducido, r[1], r[2])
    return None


def revisar_linea(ficha: FichaPersonajes, original: str, traducido: str, info: InfoLinea | None,
                  archivo: str, dudosas: bool = False, perfil_nombres=None,
                  contexto: str = "", ctx: ContextoLinea | None = None,
                  oyentes: list[Personaje] | None = None, genero_oyente: str | None = None) -> list[Hallazgo]:
    """``revisar_par`` y, con ``perfil_nombres`` (un ``config.Perfil``), también restaura los nombres
    protegidos que la traducción perdió ("Jasmine" traducido como "Jazmín"). 0, 1 o 2 hallazgos:
    si la línea es dudosa de género Y tiene un nombre que restaurar, salen los dos."""
    h = revisar_par(ficha, original, traducido, info, archivo, dudosas, ctx, oyentes, genero_oyente)
    hallazgos = [h] if h is not None else []
    if perfil_nombres is not None and traducido and traducido != original:
        base = h.propuesta if h is not None and h.tipo in (CORREGIBLE, PROBABLE) else traducido
        restaurado = perfil_nombres.restaurar_nombres(original, base)
        if restaurado != base:
            if h is not None and h.tipo == PROBABLE:
                # El nombre se restaura siempre; la 2.ª persona, solo con --segunda.
                h.propuesta = restaurado
                h.motivo = f"{h.motivo}; {_MOTIVO_NOMBRE}"
                hallazgos.insert(0, Hallazgo(archivo, CORREGIBLE, h.hablante, original, traducido,
                                             perfil_nombres.restaurar_nombres(original, traducido), _MOTIVO_NOMBRE))
            elif h is not None and h.tipo == CORREGIBLE:
                h.propuesta = restaurado
                h.motivo = f"{h.motivo}; {_MOTIVO_NOMBRE}" if h.motivo else _MOTIVO_NOMBRE
            else:
                hallazgos.insert(0, Hallazgo(archivo, CORREGIBLE, h.hablante if h else "", original, traducido,
                                             restaurado, _MOTIVO_NOMBRE))
    for x in hallazgos:
        x.contexto = contexto
    return hallazgos


def _propuesta(hallazgos: list[Hallazgo], segunda: bool = False) -> str | None:
    """Texto que se escribe con --corregir (None = no tocar). Con ``segunda`` también los 'probable'."""
    if segunda:
        probable = next((h.propuesta for h in hallazgos if h.tipo == PROBABLE), None)
        if probable is not None:
            return probable
    return next((h.propuesta for h in hallazgos if h.tipo == CORREGIBLE), None)


# --------------------------------------------------------------------------- RPG Maker
class _TraductorAuditoria:
    """Lo mínimo que necesita InyectorRPGMaker para reinyectar textos (perfil con la ficha)."""

    def __init__(self, perfil):
        self.perfil = perfil


def _copia_seguridad(ruta: Path) -> None:
    copia = ruta.with_name(ruta.name + ".auditoria.bak")
    if not copia.exists():
        shutil.copy2(ruta, copia)


def _escribir_atomico(ruta: Path, texto: str, encoding: str = "utf-8") -> None:
    tmp = ruta.with_name(ruta.name + ".tmp")
    tmp.write_text(texto, encoding=encoding)
    os.replace(tmp, ruta)


def auditar_rpgmaker(ruta_juego: Path, ficha: FichaPersonajes, perfil=None,
                     corregir: bool = False, dudosas: bool = False,
                     nombres: bool = False, segunda: bool = False) -> tuple[list[Hallazgo], list[str]]:
    """Audita los JSON traducidos de RPG Maker frente a sus ``.json.bak`` originales.
    ``nombres``: restaurar también los nombres protegidos del perfil.
    ``segunda``: con ``corregir``, aplicar también la 2.ª persona 'probable' (sin nombrar a quien escucha)."""
    hallazgos: list[Hallazgo] = []
    avisos: list[str] = []
    perfil = perfil if perfil is not None else config.Perfil(personajes=ficha)
    inyector = InyectorRPGMaker(ruta_juego, _TraductorAuditoria(perfil))
    carpeta = inyector.obtener_carpeta_datos()
    if carpeta is None:
        return hallazgos, ["No se encontró la carpeta de datos de RPG Maker."]
    for traducido_json in sorted(carpeta.glob("*.json")):
        original_json = traducido_json.with_suffix(".json.bak")
        if not original_json.exists():
            continue
        try:
            orig = json.loads(original_json.read_text(encoding="utf-8-sig"))
            trad = json.loads(traducido_json.read_text(encoding="utf-8-sig"))
        except (OSError, json.JSONDecodeError) as e:
            avisos.append(f"{traducido_json.name}: no se pudo leer ({e}).")
            continue
        pares_o = inyector.extraer_con_info(orig)
        pares_t = inyector.extraer_con_info(trad)
        if len(pares_o) != len(pares_t):
            avisos.append(f"{traducido_json.name}: el original y la traducción no están alineados "
                          f"({len(pares_o)} frente a {len(pares_t)} textos); se omite.")
            continue
        finales = [t for t, _ in pares_t]
        textos_o = [o for o, _ in pares_o]
        contextos = [resolver_linea(ficha, o, info) for o, info in pares_o]
        cambios = 0
        for i, ((o, info), (t, _)) in enumerate(zip(pares_o, pares_t)):
            hs = revisar_linea(ficha, o, t, info, traducido_json.name, dudosas,
                               perfil if nombres else None, _contexto(textos_o, i),
                               contextos[i], hablantes_cerca(contextos, i))
            if not hs:
                continue
            hallazgos += hs
            propuesta = _propuesta(hs, segunda)
            if propuesta is not None:
                finales[i] = propuesta
                cambios += 1
        if corregir and cambios:
            nuevo = copy.deepcopy(trad)
            inyector._inyectar(nuevo, iter(finales))
            comprobado = [t for t, _ in inyector.extraer_con_info(nuevo)]
            if comprobado != finales:
                diferentes = sum(1 for a, b in zip(comprobado, finales) if a != b)
                avisos.append(f"{traducido_json.name}: la reinyección no coincide ({diferentes} textos); "
                              "NO se modifica el archivo.")
                continue
            _copia_seguridad(traducido_json)
            _escribir_atomico(traducido_json, json.dumps(nuevo, ensure_ascii=False))
            log.info("  ✔ %s: %d correcciones de género aplicadas.", traducido_json.name, cambios)
    return hallazgos, avisos


# --------------------------------------------------------------------------- CSV
def _separar_celda(texto: str) -> tuple[str, str]:
    m = PATRON_PREFIJO.match(texto)
    prefijo = m.group(0) if m else ""
    return prefijo, texto[len(prefijo):]


def auditar_csv(ruta_juego: Path, ficha: FichaPersonajes, corregir: bool = False,
                dudosas: bool = False, perfil_nombres=None,
                segunda: bool = False) -> tuple[list[Hallazgo], list[str]]:
    """Audita los CSV de localización traducidos frente a sus ``.csv.original``.
    ``perfil_nombres``: perfil cuyos nombres protegidos se restauran (None = no tocar nombres).
    ``segunda``: con ``corregir``, aplicar también la 2.ª persona 'probable'."""
    hallazgos: list[Hallazgo] = []
    avisos: list[str] = []
    for original in sorted(ruta_juego.rglob("*.csv.original")):
        actual = original.with_name(original.name[:-len(".original")])
        if not actual.exists():
            continue
        _, lineas_o = leer_lineas(original)
        bom, lineas_t = leer_lineas(actual)
        if not lineas_o or len(lineas_o) != len(lineas_t):
            avisos.append(f"{actual.name}: no coincide en líneas con el original; se omite.")
            continue
        delim, _, col = analizar_cabecera(lineas_o)
        if col is None:
            continue
        cambiado = False
        celdas_o = []
        infos: list[InfoLinea | None] = []
        for linea in lineas_o:
            p, _ = partir(linea, delim)
            celdas_o.append(_separar_celda(p[col])[1].replace("\\n", " ") if len(p) > col else "")
            m = PATRON_NOMBRE_HABLANTE.match(p[col]) if len(p) > col else None
            infos.append(InfoLinea(hablante=m.group(2)) if m else None)
        contextos = [resolver_linea(ficha, c, info) for c, info in zip(celdas_o, infos)]
        contextos[0] = ContextoLinea()  # la cabecera no es una frase
        for i in range(1, len(lineas_o)):
            p_o, _ = partir(lineas_o[i], delim)
            p_t, cr = partir(lineas_t[i], delim)
            if len(p_o) <= col or len(p_t) != len(p_o):
                continue
            pref_t, cuerpo_t = _separar_celda(p_t[col])
            hs = revisar_linea(ficha, celdas_o[i], cuerpo_t, infos[i], actual.name, dudosas, perfil_nombres,
                               _contexto(celdas_o[1:], i - 1), contextos[i], hablantes_cerca(contextos, i))
            if not hs:
                continue
            hallazgos += hs
            propuesta = _propuesta(hs, segunda)
            if corregir and propuesta is not None:
                p_t[col] = pref_t + propuesta
                lineas_t[i] = unir(p_t, delim, cr)
                cambiado = True
        if cambiado:
            _copia_seguridad(actual)
            escribir_lineas(actual, bom, lineas_t)
            log.info("  ✔ %s: correcciones de género aplicadas.", actual.name)
    return hallazgos, avisos


# --------------------------------------------------------------------------- XUnity
def buscar_archivos_xunity(ruta_juego: Path) -> list[Path]:
    encontrados: list[Path] = []
    for base in (ruta_juego / "BepInEx" / "Translation", ruta_juego / "Translation", ruta_juego / "AutoTranslator"):
        if base.is_dir():
            encontrados.extend(sorted(base.glob("*/Text/_AutoGeneratedTranslations.txt")))
    return encontrados


def _personaje_de(ficha: FichaPersonajes, h) -> Personaje | None:
    """Personaje de la ficha que corresponde a un hablante de la tabla de Unity (o uno nuevo con el género
    que dice el juego). None si no se sabe ni el nombre ni el género."""
    if h.nombre:
        p = ficha.buscar(h.nombre)
        if p is not None:
            return p
    if h.genero and h.genero in (HOMBRE, MUJER):
        return Personaje(nombre=h.nombre or "Hablante", genero=h.genero, rol="extra")
    return Personaje(nombre=h.nombre, genero="desconocido", rol="extra") if h.nombre else None


def auditar_xunity(ruta_txt: Path, ficha: FichaPersonajes, corregir: bool = False,
                   dudosas: bool = False, perfil_nombres=None, hablantes=None,
                   segunda: bool = False) -> tuple[list[Hallazgo], list[str]]:
    """Audita un ``_AutoGeneratedTranslations.txt``.

    Sin ``hablantes``: solo pensamientos, nombrados y vocativos. Con ``hablantes`` (la tabla
    ``TablaHablantes`` que se saca de los archivos del juego, ver ``traductor/unity_dialogos.py``) se sabe
    quién dice cada frase y quiénes hablan en su conversación, así que también se revisan la 1.ª persona, la
    2.ª sin nombrar y el plural de grupo, igual que en RPG Maker.

    Revisa cada línea (también las claves repetidas) y, con ``corregir``, reescribe SOLO las líneas
    corregidas: el resto del archivo queda byte a byte igual (ver ``xunity.editar_lineas``).
    El contexto del informe son las frases vecinas en el archivo (el orden en que salieron en el juego).
    """
    hallazgos: list[Hallazgo] = []
    propuestas: dict[tuple[str, str], str] = {}
    revisados: set[tuple[str, str]] = set()
    orden = xunity.leer_pares(ruta_txt)
    originales = [o for o, _ in orden]
    posicion: dict[tuple[str, str], int] = {}
    for i, par in enumerate(orden):
        posicion.setdefault(par, i)

    def revisar(original: str, traducido: str) -> str | None:
        par = (original, traducido)
        if par not in revisados:  # una clave repetida con la misma traducción se informa una vez
            revisados.add(par)
            i = posicion.get(par)
            info = hablantes.info(original) if hablantes is not None else None
            ctx = oyentes = None
            if info is not None:
                ctx = resolver_linea(ficha, original, info)
                presentes = [_personaje_de(ficha, h) for h in hablantes.escena(original)]
                presentes = [p for p in presentes if p is not None]
                oyentes = presentes if presentes else None   # sin escena conocida no se adivina quién escucha
            pista_oyente = getattr(hablantes, "genero_oyente", None)
            hs = revisar_linea(ficha, original, traducido, info, ruta_txt.name, dudosas, perfil_nombres,
                               _contexto(originales, i) if i is not None else "", ctx, oyentes,
                               pista_oyente(original) if pista_oyente is not None else None)
            hallazgos.extend(hs)
            propuesta = _propuesta(hs, segunda)
            if propuesta is not None:
                propuestas[par] = propuesta
        return propuestas.get(par)

    lineas = xunity.editar_lineas(ruta_txt, revisar, escribir=False)
    if corregir and lineas:
        _copia_seguridad(ruta_txt)
        xunity.editar_lineas(ruta_txt, lambda o, t: propuestas.get((o, t)))
        log.info("  ✔ %s: %d líneas corregidas (reinicia el juego para verlas).", ruta_txt.name, lineas)
    return hallazgos, []


# --------------------------------------------------------------------------- Informe
def guardar_informe(hallazgos: list[Hallazgo], ruta: Path) -> Path:
    ruta.parent.mkdir(parents=True, exist_ok=True)
    with open(ruta, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(["archivo", "tipo", "hablante", "original", "traducido", "propuesta", "motivo", "contexto"])
        for h in hallazgos:
            w.writerow([h.archivo, h.tipo, h.hablante, h.original, h.traducido, h.propuesta, h.motivo, h.contexto])
    return ruta


def resumen(hallazgos: list[Hallazgo], corregir: bool, segunda: bool = False) -> str:
    tipos = Counter(h.tipo for h in hallazgos)
    lineas = [f"Hallazgos: {len(hallazgos)} ({tipos[CORREGIBLE]} con corrección automática"
              f"{' APLICADA' if corregir else ''}, {tipos[PROBABLE]} probables de 2.ª persona"
              f"{' APLICADOS' if corregir and segunda else ''}, {tipos[REVISAR]} para revisar a mano)"]
    for h in [h for h in hallazgos if h.tipo == CORREGIBLE][:8]:
        lineas.append(f"  · [{h.archivo}] {h.traducido[:60]!r} -> {h.propuesta[:60]!r}  ({h.motivo[:50]})")
    for h in [h for h in hallazgos if h.tipo == PROBABLE][:6]:
        lineas.append(f"  ~ [{h.archivo}] {h.traducido[:60]!r} -> {h.propuesta[:60]!r}  ({h.hablante})")
    for h in [h for h in hallazgos if h.tipo == REVISAR][:4]:
        lineas.append(f"  ? [{h.archivo}] {h.traducido[:70]!r}  ({h.motivo[:60]})")
    return "\n".join(lineas)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Auditoría de género de un juego traducido (usa personajes.json).")
    parser.add_argument("--ruta", required=True, help="Carpeta del juego")
    parser.add_argument("--juego", help="Perfil en workspace/<juego>/ (por defecto se deduce de la carpeta)")
    parser.add_argument("--corregir", action="store_true", help="Aplicar las correcciones automáticas (con copia de seguridad)")
    parser.add_argument("--salida", help="CSV del informe (por defecto workspace/<juego>/auditoria_genero.csv)")
    parser.add_argument("--xunity", help="Ruta de un _AutoGeneratedTranslations.txt concreto")
    parser.add_argument("--dudosas", action="store_true",
                        help="Listar también (sin corregir) líneas sin hablante cuya 1.ª persona contradice al protagonista")
    parser.add_argument("--segunda", action="store_true",
                        help="Con --corregir, aplicar también la 2.ª persona 'probable': la frase no nombra a quien "
                             "escucha, pero todos los que están en la escena son del otro género "
                             "('¿Estás segura?' a un protagonista hombre). Revisa antes el informe")
    parser.add_argument("--nombres", action="store_true",
                        help="Restaurar también los nombres protegidos que se tradujeron (nombres_protegidos.json): "
                             "'Jazmín' -> 'Jasmine'")
    parser.add_argument("--debug", action="store_true", help="Mostrar logs detallados de depuración")
    args = parser.parse_args(argv)
    configurar_logging(detallado=args.debug)

    ruta_juego = Path(args.ruta)
    if not ruta_juego.exists():
        log.error("No existe la carpeta del juego: %s", ruta_juego)
        return 1
    juego = config.resolver_juego(args.juego, ruta_juego)
    ficha = FichaPersonajes.cargar(ruta_ficha(config.carpeta_juego(juego)))
    if ficha is None or not ficha.personajes:
        log.error("El juego '%s' no tiene ficha de personajes. Ejecuta antes el Paso 0:\n"
                  "  python 0_analizar_juego.py --ruta \"%s\"", juego, ruta_juego)
        return 2
    perfil = config.cargar_perfil(juego, auto_crear=False)
    log.info("Ficha de personajes: %s", ficha.resumen())

    hallazgos: list[Hallazgo] = []
    avisos: list[str] = []
    perfil_nombres = perfil if args.nombres else None
    archivos_xunity = [Path(args.xunity)] if args.xunity else buscar_archivos_xunity(ruta_juego)
    if archivos_xunity:
        tabla = TablaHablantes.cargar(ruta_tabla(juego))
        if len(tabla):
            log.info("Quién habla en Unity: %d frases con hablante (%s)", len(tabla), ruta_tabla(juego).name)
        else:
            # Sin objetos Dialogue: quizá las tablas de texto del juego traen ruso/ucraniano, que dicen el
            # sexo de quien habla y de quien escucha
            from traductor.motores.unity_tablas import PistasTablas, extraer_tablas
            pistas = PistasTablas(extraer_tablas(ruta_juego), ficha)
            if len(pistas):
                log.info("Pistas de sexo de las tablas del juego (ruso/ucraniano): %d", len(pistas))
                tabla = pistas
        for txt in archivos_xunity:
            h, a = auditar_xunity(txt, ficha, corregir=args.corregir, dudosas=args.dudosas,
                                  perfil_nombres=perfil_nombres, hablantes=tabla if len(tabla) else None,
                                  segunda=args.segunda)
            hallazgos += h
            avisos += a
    else:
        h, a = auditar_rpgmaker(ruta_juego, ficha, perfil, corregir=args.corregir, dudosas=args.dudosas,
                                nombres=args.nombres, segunda=args.segunda)
        hallazgos += h
        avisos += a
        h, a = auditar_csv(ruta_juego, ficha, corregir=args.corregir, dudosas=args.dudosas,
                           perfil_nombres=perfil_nombres, segunda=args.segunda)
        hallazgos += h
        avisos += a

    salida = Path(args.salida) if args.salida else config.carpeta_juego(juego) / "auditoria_genero.csv"
    guardar_informe(hallazgos, salida)
    print(resumen(hallazgos, args.corregir, args.segunda))
    for aviso in avisos:
        print(f"⚠ {aviso}")
    print(f"Informe: {salida}")
    if hallazgos and not args.corregir:
        print("Para aplicar las correcciones automáticas vuelve a ejecutar con --corregir "
              "(se guarda una copia .auditoria.bak de cada archivo modificado).")
    if any(h.tipo == PROBABLE for h in hallazgos) and not (args.corregir and args.segunda):
        print("Los 'probable' (2.ª persona sin nombrar a quien escucha) solo se aplican con --corregir --segunda; "
              "revísalos antes en el informe.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
