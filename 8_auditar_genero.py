"""8_auditar_genero.py — Auditoría de género de un juego YA traducido.

Con la ficha de personajes (``workspace/<juego>/personajes.json``, Paso 0) revisa la traducción y
propone (o aplica con ``--corregir``) la concordancia correcta:

  - 1.ª persona según quien habla: Laura (mujer) "Estoy cansado" -> "Estoy cansada".
  - 2.ª persona y saludos cuando se nombra a quien escucha: "¿Estás listo, Chloe?" -> "lista".
  - 2.ª persona SIN nombrar a quien escucha: se mira quién habla en las frases de alrededor. Si todos
    los que pueden estar escuchando son del mismo género y la traducción usa el contrario, es un fallo
    "probable" (Laura a solas con un protagonista hombre: "¿Estás segura?" -> "seguro"). Solo se
    aplica con ``--segunda``; si cerca hay alguien del género de la traducción, no se señala.
  - 3.ª persona y títulos con nombre: "Ana está cansado", "mi amigo Ana".
  - Pensamientos "(...)" sin hablante -> son del protagonista.

Formatos: RPG Maker (``*.json`` traducido frente a su ``*.json.bak`` original), CSV de
localización (``*.csv`` frente a ``*.csv.original``) y XUnity (``_AutoGeneratedTranslations.txt``).
Sin ``--corregir`` NO modifica nada: solo genera el informe CSV (``;`` y UTF-8 con BOM, para Excel),
con una columna de contexto (frase anterior y siguiente) para revisar a mano las dudosas.
Con ``--nombres`` también restaura los nombres protegidos que se tradujeron ("Jazmín" -> "Jasmine").

Uso:
    python 8_auditar_genero.py --ruta "J:\\Juegos\\MiJuego"
    python 8_auditar_genero.py --ruta "J:\\Juegos\\MiJuego" --corregir
    python 8_auditar_genero.py --ruta "J:\\Juegos\\MiJuego" --corregir --segunda
    python 8_auditar_genero.py --ruta "J:\\Juegos\\MiJuego" --dudosas --nombres
    python 8_auditar_genero.py --ruta "..." --xunity "...\\Translation\\es\\Text\\_AutoGeneratedTranslations.txt"
"""
