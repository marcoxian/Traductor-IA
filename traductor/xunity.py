"""Lectura/escritura del formato de traducciones de XUnity.AutoTranslator.

Formato de cada línea:  ``original=traducción``

XUnity exige escapar ciertos caracteres (comprobado contra
``XUnity.AutoTranslator.Plugin.Core.Utilities.TextHelper.Encode`` del propio DLL):

    \\  -> \\\\        salto de línea -> \\n       retorno de carro -> \\r
    =   -> \\=         //             -> \\/\\/  (``//`` al inicio de línea es un comentario)

Si una línea tiene un ``=`` sin escapar además del separador, XUnity la **descarta entera**.
Antes los scripts escribían ``Giggle [pic=2]=Risita`` y XUnity ignoraba miles de entradas.
"""
from __future__ import annotations

import codecs
import logging
import os
import re
from pathlib import Path
from typing import Callable, Iterable, Mapping

log = logging.getLogger(__name__)

# Marcas del Dialogue System de Pixel Crushers que el juego procesa ANTES de pintar el texto
# (retratos, posición del panel, etc.). Lo que ve XUnity en pantalla ya no las contiene.
PATRON_MARCAS_PIXEL_CRUSHERS = re.compile(
    r"\s*\[(?:pic|picc|pica|position|panel)=[^\]\s]*\]|\s*\[(?:f|a|auto|nosubtitle)\]",
    re.IGNORECASE,
)


# --------------------------------------------------------------------------- Escapado
def escapar(texto: str) -> str:
    """Equivalente a ``TextHelper.Encode`` de XUnity."""
    salida: list[str] = []
    i, n = 0, len(texto)
    while i < n:
        c = texto[i]
        if c == "\\":
            salida.append("\\\\")
        elif c == "\n":
            salida.append("\\n")
        elif c == "\r":
            salida.append("\\r")
        elif c == "=":
            salida.append("\\=")
        elif c == "/" and i + 1 < n and texto[i + 1] == "/":
            # XUnity escapa las parejas '//' (si no, las tomaría como comentario): '///' -> '\/\//'
            salida.append("\\/\\/")
            i += 1
        else:
            salida.append(c)
        i += 1
    return "".join(salida)


_DESESCAPES = {"n": "\n", "r": "\r", "\\": "\\", "=": "=", "/": "/", "t": "\t"}


def desescapar(texto: str) -> str:
    salida: list[str] = []
    i, n = 0, len(texto)
    while i < n:
        c = texto[i]
        if c == "\\" and i + 1 < n and texto[i + 1] in _DESESCAPES:
            salida.append(_DESESCAPES[texto[i + 1]])
            i += 2
            continue
        salida.append(c)
        i += 1
    return "".join(salida)


def _posicion_separador(linea: str) -> int | None:
    """Posición del ``=`` separador o None si XUnity no aceptaría la línea (comentario, vacía,
    ``//`` sin escapar o más de un ``=`` sin escapar)."""
    if not linea or linea.startswith("//"):
        return None
    separadores = []
    i = 0
    while i < len(linea):
        if linea[i] == "\\":
            i += 2
            continue
        if linea[i] == "=":
            separadores.append(i)
        elif linea[i] == "/" and i + 1 < len(linea) and linea[i + 1] == "/":
            return None  # XUnity trata un '//' sin escapar como inicio de comentario
        i += 1
    return separadores[0] if len(separadores) == 1 else None


def leer_linea(linea: str) -> tuple[str, str] | None:
    """Parte una línea por el primer ``=`` NO escapado. Devuelve None si es inválida/comentario
    (mismo criterio que XUnity: más de un ``=`` sin escapar invalida la línea)."""
    linea = linea.rstrip("\r\n")
    pos = _posicion_separador(linea)
    if pos is None:
        return None
    return desescapar(linea[:pos]), desescapar(linea[pos + 1:])


def formatear_linea(original: str, traduccion: str) -> str:
    return f"{escapar(original)}={escapar(traduccion)}"


# --------------------------------------------------------------------------- Archivo
def leer_traducciones(ruta: Path) -> dict[str, str]:
    """Lee un ``_AutoGeneratedTranslations.txt``. Ignora comentarios y líneas que XUnity no aceptaría."""
    if not ruta.exists():
        return {}
    datos: dict[str, str] = {}
    invalidas = 0
    for linea in ruta.read_text(encoding="utf-8-sig", errors="replace").splitlines():
        par = leer_linea(linea)
        if par is None:
            if linea.strip() and not linea.startswith("//"):
                invalidas += 1
            continue
        datos[par[0]] = par[1]
    if invalidas:
        log.info("XUnity: %d líneas inválidas ignoradas en %s (se reescribirán bien escapadas).",
                 invalidas, ruta.name)
    return datos


def leer_pares(ruta: Path) -> list[tuple[str, str]]:
    """Todas las líneas válidas EN ORDEN (con claves repetidas). XUnity va añadiendo las frases según
    salen en pantalla, así que las vecinas de una línea son su contexto en el juego."""
    if not ruta.exists():
        return []
    pares = []
    for linea in ruta.read_text(encoding="utf-8-sig", errors="replace").splitlines():
        par = leer_linea(linea)
        if par is not None:
            pares.append(par)
    return pares


def escribir_traducciones(ruta: Path, traducciones: Mapping[str, str]) -> None:
    """Escribe el archivo de forma atómica (tmp + replace) con todas las claves escapadas."""
    ruta.parent.mkdir(parents=True, exist_ok=True)
    lineas = [formatear_linea(o, t) for o, t in traducciones.items() if o and t is not None]
    tmp = ruta.with_name(ruta.name + ".tmp")
    tmp.write_text("\n".join(lineas) + "\n", encoding="utf-8-sig")
    os.replace(tmp, ruta)


_SALTO_FISICO = re.compile(r"(\r\n|\r|\n)")  # lo mismo que corta StreamReader.ReadLine de .NET


def editar_lineas(ruta: Path, funcion: Callable[[str, str], str | None], *, escribir: bool = True) -> int:
    """Edición quirúrgica: llama a ``funcion(original, traduccion)`` con CADA línea válida y, si
    devuelve una traducción distinta, reescribe solo esa línea (la clave se deja tal cual estaba).

    Todo lo demás queda byte a byte igual: BOM o no, saltos ``\\r\\n``, líneas en blanco, comentarios,
    claves duplicadas y líneas que XUnity ignora. ``escribir_traducciones`` en cambio regenera el
    archivo entero (deduplica y descarta lo inválido), que no es lo que se quiere al retocar un juego
    ya traducido. Devuelve cuántas líneas cambian; con ``escribir=False`` no toca el archivo.
    """
    if not ruta.exists():
        return 0
    datos = ruta.read_bytes()
    bom = datos.startswith(codecs.BOM_UTF8)
    texto = datos[len(codecs.BOM_UTF8):] if bom else datos
    # surrogateescape: los bytes que no son UTF-8 válido vuelven a escribirse idénticos
    partes = _SALTO_FISICO.split(texto.decode("utf-8", errors="surrogateescape"))
    cambios = 0
    for i in range(0, len(partes), 2):  # en los índices impares están los saltos de línea
        linea = partes[i]
        pos = _posicion_separador(linea)
        if pos is None:
            continue
        traduccion = desescapar(linea[pos + 1:])
        nueva = funcion(desescapar(linea[:pos]), traduccion)
        if nueva is None or nueva == traduccion:
            continue
        partes[i] = linea[:pos + 1] + escapar(nueva)
        cambios += 1
    if escribir and cambios:
        salida = "".join(partes).encode("utf-8", errors="surrogateescape")
        tmp = ruta.with_name(ruta.name + ".tmp")
        tmp.write_bytes((codecs.BOM_UTF8 if bom else b"") + salida)
        os.replace(tmp, ruta)
    return cambios


def fusionar_y_guardar(ruta: Path, nuevas: Mapping[str, str]) -> dict[str, str]:
    """Mezcla ``nuevas`` con lo que ya hubiera en el archivo (p. ej. lo que XUnity añadió en vivo)
    y lo guarda. Las nuevas ganan. Devuelve el diccionario final."""
    datos = leer_traducciones(ruta)
    datos.update(nuevas)
    escribir_traducciones(ruta, datos)
    return datos


# --------------------------------------------------------------------------- Variantes de clave
def quitar_marcas_pixel_crushers(texto: str) -> str:
    return PATRON_MARCAS_PIXEL_CRUSHERS.sub("", texto).strip()


def colapsar_espacios(texto: str) -> str:
    return re.sub(r"\s+", " ", texto).strip()


def variantes_clave(original: str, traduccion: str) -> dict[str, str]:
    """Entradas a escribir para un par: la exacta, la que realmente se ve en pantalla (sin marcas de
    Pixel Crushers) y la versión con saltos/espacios colapsados."""
    salida = {original: traduccion}
    sin_marcas_o = quitar_marcas_pixel_crushers(original)
    sin_marcas_t = quitar_marcas_pixel_crushers(traduccion)
    if sin_marcas_o and sin_marcas_o != original and sin_marcas_t:
        salida[sin_marcas_o] = sin_marcas_t
    for o, t in list(salida.items()):
        oc = colapsar_espacios(o)
        if oc and oc != o and oc not in salida:
            salida[oc] = colapsar_espacios(t)
    return salida


def construir_entradas(pares: Iterable[tuple[str, str]]) -> dict[str, str]:
    """Aplica ``variantes_clave`` a muchos pares, descartando los que no cambian nada."""
    salida: dict[str, str] = {}
    for original, traduccion in pares:
        if not original or not traduccion or original.strip() == traduccion.strip():
            continue
        salida.update(variantes_clave(original, traduccion))
    return salida
