"""Inyector de configuración para Unity y XUnity.AutoTranslator."""
from __future__ import annotations

import configparser
import logging
import re
from pathlib import Path

from .. import config, xunity
from ..genero import marcas_genero
from ..personajes import aplicar_concordancia
from ..texto import _PALABRAS_INGLES, evaluar_traduccion, gravedad, tiene_texto_visible
from ..unity_dialogos import TablaHablantes, preparar_tabla

log = logging.getLogger(__name__)

PUERTO_PROXY_DEFECTO = 11435
_ZALGO = re.compile(r"[̀-ͯ᷀-᷿⃐-⃿︠-︯]")
_URL = re.compile(r"^\s*(?:https?://|www\.)\S*\s*$", re.IGNORECASE)


def _sin_espacios(texto: str) -> str:
    return re.sub(r"\s+", " ", texto).strip().lower()


def inyectar_unity(ruta_juego: Path, modelo: str = config.MODELO_POR_DEFECTO, endpoint: str = config.OLLAMA_URL,
                   puerto_proxy: int = PUERTO_PROXY_DEFECTO, juego: str | None = None) -> Path:
    """Configura el framework BepInEx y XUnity.AutoTranslator para usar la IA local a través de ollama_proxy.

    Crea o actualiza AutoTranslatorConfig.ini apuntando a CustomTranslate (http://127.0.0.1:11435/translate).
    """
    log.info("Configurando framework BepInEx y XUnity.AutoTranslator...")

    auto_translator_dir = ruta_juego / "BepInEx" / "config"
    auto_translator_dir.mkdir(parents=True, exist_ok=True)
    config_path = auto_translator_dir / "AutoTranslatorConfig.ini"

    cfg = configparser.ConfigParser(strict=False)
    cfg.optionxform = str  # Preserva mayúsculas y minúsculas

    if config_path.exists():
        leido = False
        for enc in ("utf-8-sig", "utf-8", "utf-16", "cp1252"):
            try:
                cfg.read(config_path, encoding=enc)
                leido = True
                break
            except Exception as e:
                log.debug("No se pudo leer config con %s: %s", enc, e)
        if not leido:
            log.warning("No se pudo leer la configuración previa de AutoTranslator; se generará una limpia.")

    # 1. Configurar servicio CustomTranslate
    if "Service" not in cfg:
        cfg["Service"] = {}
    cfg["Service"]["Endpoint"] = "CustomTranslate"
    cfg["Service"]["FallbackEndpoint"] = ""

    # 2. Configurar endpoint Custom (proxy local)
    if "Custom" not in cfg:
        cfg["Custom"] = {}
    cfg["Custom"]["Url"] = f"http://127.0.0.1:{puerto_proxy}/translate"
    cfg["Custom"]["EnableShortDelay"] = "True"
    cfg["Custom"]["DisableSpamChecks"] = "True"

    # Eliminar sección obsoleta si existía
    if "CustomHTTP" in cfg:
        del cfg["CustomHTTP"]

    # 3. Configurar idioma general (en -> es)
    if "General" not in cfg:
        cfg["General"] = {}
    cfg["General"]["Language"] = "es"
    cfg["General"]["FromLanguage"] = "en"

    # 4. Configurar rutas de archivos
    if "Files" not in cfg:
        cfg["Files"] = {}
    cfg["Files"]["Directory"] = r"Translation\{Lang}\Text"
    cfg["Files"]["OutputFile"] = r"Translation\{Lang}\Text\_AutoGeneratedTranslations.txt"
    cfg["Files"]["SubstitutionFile"] = r"Translation\{Lang}\Text\_Substitutions.txt"
    cfg["Files"]["PreprocessorsFile"] = r"Translation\{Lang}\Text\_Preprocessors.txt"
    cfg["Files"]["PostprocessorsFile"] = r"Translation\{Lang}\Text\_Postprocessors.txt"

    # 5. Configurar TextFrameworks (TMP, UGUI, etc.)
    if "TextFrameworks" not in cfg:
        cfg["TextFrameworks"] = {}
    cfg["TextFrameworks"]["EnableUGUI"] = "True"
    cfg["TextFrameworks"]["EnableTextMeshPro"] = "True"
    cfg["TextFrameworks"]["EnableUIElements"] = "True"
    cfg["TextFrameworks"]["EnableNGUI"] = "True"
    cfg["TextFrameworks"]["EnableIMGUI"] = "False"
    cfg["TextFrameworks"]["EnableTextMesh"] = "False"
    cfg["TextFrameworks"]["EnableFairyGUI"] = "True"

    # 6. Comportamiento (captura palabras cortas como botones y diálogos breves)
    if "Behaviour" not in cfg:
        cfg["Behaviour"] = {}
    cfg["Behaviour"]["MinDialogueChars"] = "1"
    cfg["Behaviour"]["MaxCharactersPerTranslation"] = "1000"
    cfg["Behaviour"]["EnableBatching"] = "False"
    cfg["Behaviour"]["UseStaticTranslations"] = "True"
    cfg["Behaviour"]["ReloadTranslationsOnFileChange"] = "True"
    cfg["Behaviour"]["EnableSilentMode"] = "False"
    cfg["Behaviour"]["HandleRichText"] = "True"
    cfg["Behaviour"]["EnableUIResizing"] = "True"

    # 7. Depuración
    if "Debug" not in cfg:
        cfg["Debug"] = {}
    cfg["Debug"]["EnableConsole"] = "True"

    # 8. Guardar sin espacios alrededor del '=' para máxima compatibilidad con XUnity
    with open(config_path, "w", encoding="utf-8") as f:
        cfg.write(f, space_around_delimiters=False)

    log.info("¡Éxito! Archivo de AutoTranslator generado limpiamente en: %s", config_path)

    # 9. Activar consola de BepInEx si existe BepInEx.cfg
    bepinex_cfg_path = auto_translator_dir / "BepInEx.cfg"
    if bepinex_cfg_path.exists():
        try:
            content = bepinex_cfg_path.read_text(encoding="utf-8-sig")
            new_content = re.sub(
                r'(\[Logging\.Console\][\s\S]*?Enabled\s*=\s*)(false|true)',
                r'\g<1>true',
                content,
                flags=re.IGNORECASE,
            )
            if new_content != content:
                bepinex_cfg_path.write_text(new_content, encoding="utf-8")
                log.info("Consola de BepInEx activada en: %s", bepinex_cfg_path)
        except Exception as e:
            log.warning("No se pudo actualizar consola en BepInEx.cfg: %s", e)

    # 10. Instalar plugin de auto-arranque del proxy para que el usuario no tenga que abrirlo manualmente
    plugin_fuente = Path(__file__).resolve().parent / "recursos" / "AutoProxyPlugin.dll"
    if plugin_fuente.exists():
        plugins_dest = ruta_juego / "BepInEx" / "plugins" / "AutoProxyLauncher"
        plugins_dest.mkdir(parents=True, exist_ok=True)
        import shutil
        dest_dll = plugins_dest / "AutoProxyPlugin.dll"
        try:
            shutil.copy2(plugin_fuente, dest_dll)
            # El plugin lee aquí dónde está el Traductor IA (no lleva ninguna ruta dentro)
            (plugins_dest / "traductor_ia_ruta.txt").write_text(str(config.RAIZ), encoding="utf-8")
            log.info("Plugin de auto-arranque de IA instalado en: %s", dest_dll)
        except Exception as e:
            log.warning("No se pudo copiar AutoProxyPlugin.dll: %s", e)

    # 11. El plugin pasa al proxy el nombre de la carpeta del juego; si no da el perfil (p. ej. está en chino),
    # el perfil recuerda su carpeta para que el proxy lo encuentre
    if juego:
        config.guardar_ajustes_juego(juego, carpeta_juego=Path(ruta_juego).name)

    # 12. Quién dice cada frase, si el juego lo guarda en sus archivos (lo usa el proxy para el género)
    try:
        preparar_tabla(juego, ruta_juego)
    except Exception as e:  # nunca impide traducir
        log.warning("No se pudo leer quién habla en los archivos del juego: %s", e)

    return config_path


def archivo_xunity(ruta_juego: Path) -> Path:
    return Path(ruta_juego) / "BepInEx" / "Translation" / "es" / "Text" / "_AutoGeneratedTranslations.txt"


def repasar_xunity(ruta_txt: Path, translator, hablantes: TablaHablantes) -> dict[str, int]:
    """Juego de Unity ya traducido (``--solo-genero``): repasa ``_AutoGeneratedTranslations.txt`` y vuelve a
    pedir al modelo SOLO las frases que lo necesitan, ahora sabiendo quién habla si el juego lo guarda:

    - con marcas de género en 1.ª/2.ª persona ("Estoy cansado") que la concordancia no deja claras,
    - con una palabra de dos sentidos mal elegida ("cofre" por pecho) o un fallo grave (inglés, eco...).

    Si la nueva traducción no pasa la puerta de calidad se deja la de antes. Solo cambian esas líneas: el
    resto del archivo queda byte a byte igual (``xunity.editar_lineas``).
    """
    stats = {"repasadas": 0, "con_hablante": 0, "concordancia": 0, "retraducidas": 0, "sin_mejora": 0}

    def _repasar(original: str, traduccion: str) -> str | None:
        if not original.strip() or not tiene_texto_visible(original) or _ZALGO.search(original):
            return None  # el texto "glitch" (letras con marcas encima) lo deja como estaba
        if _URL.match(original):
            return None
        if _sin_espacios(traduccion) == _sin_espacios(original) and len(_PALABRAS_INGLES.findall(original)) < 2:
            return None  # igual que el original pero sin frase inglesa: gemidos, nombres, otro idioma...
        stats["repasadas"] += 1
        info = hablantes.info(original)
        if info is not None:
            stats["con_hablante"] += 1
        ctx = translator._contexto_linea(original, info)
        nueva = aplicar_concordancia(traduccion, original, ctx) if ctx is not None else traduccion

        def _fallos(texto: str) -> int:
            """Gravedad de los problemas de una traducción de esta línea (0 = ninguno)."""
            # las etiquetas no cuentan: XUnity muestra bien un "</i>" de más y retraducir por eso estropea más
            puntos = gravedad([p for p in evaluar_traduccion(original, texto) if p != "etiquetas"])
            if translator._sentido_mal(original, texto):
                puntos += 40
            if ctx is not None and info is not None and marcas_genero(texto) \
                    and not translator._compatible_con_ficha(texto, ctx):
                puntos += 50
            return puntos

        fallos_actual = _fallos(nueva)
        if fallos_actual == 0:
            if nueva != traduccion:
                stats["concordancia"] += 1
                return nueva
            return None
        try:
            otra = translator.translate(original, info=info, lanzar_error=True)
        except Exception as e:
            log.debug("Sin retraducir (%s): %s", e, original[:60])
            otra = None
        # Solo se cambia si la nueva es MEJOR (no basta con que no tenga fallos graves), y nunca por el
        # original en inglés cuando ya había una traducción ("¡Mierdaaa~!" -> "Shiiit~")
        rompe_etiquetas = bool(otra) and "etiquetas" in evaluar_traduccion(original, otra) \
            and "etiquetas" not in evaluar_traduccion(original, nueva)  # p. ej. pierde el "</b>"
        if not otra or rompe_etiquetas or _fallos(otra) >= fallos_actual or (
                _sin_espacios(otra) == _sin_espacios(original) != _sin_espacios(traduccion)):
            stats["sin_mejora"] += 1
            return nueva if nueva != traduccion else None
        if otra != traduccion:
            stats["retraducidas"] += 1
            return otra
        return None

    # Las líneas del archivo no van en el orden del diálogo: sin conversación previa (un título salía
    # traducida como la frase anterior)
    historial_antes = getattr(translator, "usar_historial", False)
    translator.usar_historial = False
    try:
        cambios = xunity.editar_lineas(ruta_txt, _repasar)
    finally:
        translator.usar_historial = historial_antes
    log.info("♻ XUnity: %d frases repasadas (%d con hablante conocido); %d cambian (%d por concordancia, "
             "%d retraducidas; %d se quedan como estaban porque la nueva no era mejor).", stats["repasadas"],
             stats["con_hablante"], cambios, stats["concordancia"], stats["retraducidas"], stats["sin_mejora"])
    stats["cambios"] = cambios
    return stats
