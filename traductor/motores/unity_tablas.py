"""Unity: traducir por adelantado las tablas de texto que el juego lleva dentro.

Muchos juegos de Unity guardan todos sus textos en ``TextAsset`` con forma de tabla (CSV o TSV) y una
columna por idioma (``ID,ZH,EN,JA,...`` o ``key\\ttw\\tjp\\ten``). Si se traduce esa columna inglesa antes
de jugar y se escribe en ``_AutoGeneratedTranslations.txt``, XUnity encuentra cada frase ya traducida: no
hay que esperar a la IA mientras se juega (solo a lo que el juego monta al vuelo, como "Día 3").

Si la tabla trae ruso o ucraniano, se usa como pista del sexo de quien habla: en esos idiomas el pasado
cambia con el sexo ("я увидел" lo dice él, "я увидела" lo dice ella). Así "I'm sure" sale "estoy segura"
cuando habla una chica aunque el juego no diga quién habla.
"""
