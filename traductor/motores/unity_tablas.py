def _genero_en(texto: str, ella: re.Pattern, el: re.Pattern) -> str | None:
    f, m = bool(ella.search(texto)), bool(el.search(texto))
    return "mujer" if f and not m else "hombre" if m and not f else None


def _votar(celdas: dict[str, str], pistas: dict[str, tuple[re.Pattern, re.Pattern]]) -> str | None:
    votos = {_genero_en(t, *pistas[c]) for c, t in celdas.items() if c in pistas and t}
    votos.discard(None)
    return votos.pop() if len(votos) == 1 else None


def genero_de_quien_habla(celdas: dict[str, str]) -> str | None:
    """'hombre'/'mujer' si las traducciones rusa/ucraniana de la fila lo dejan claro (y no se contradicen)."""
    return _votar(celdas, _PISTAS)


def genero_de_quien_escucha(celdas: dict[str, str]) -> str | None:
    """'hombre'/'mujer' de la persona a la que se habla ("ты готов" / "ты готова"), si el ruso/ucraniano lo
    deja claro y no se contradicen."""
    return _votar(celdas, _PISTAS_TU)


# --------------------------------------------------------------------------- ajustes del perfil
@dataclass
class AjustesTablas:
    """Sección ``tablas_unity`` de ``workspace/<juego>/ajustes.json``. Todo opcional:

    - ``omitir``: nombres de tabla (admite ``*``) que no se traducen (texto que el juego no enseña).
    - ``columna_hablante``: ``{patrón de tabla: nº de columna}`` con quién habla en cada fila.
    - ``hablantes``: ``{lo que pone esa columna: nombre en la ficha}``; ``""`` = no es nadie de la ficha.
    - ``variables``: ``{código: valor}`` que el juego sustituye antes de enseñar la frase
      (``{"{flag=Flag_Heroine_Name}": "Ana"}``).
    - ``otros_valores``: ``{código: [{"en": …, "es": …}]}``, lo que el juego enseña en lugar del valor principal
      en otros momentos (p. ej. "the strange girl" antes de que el jugador le ponga nombre). De cada frase
      traducida con el valor principal se saca su gemela cambiando el nombre, sin volver a llamar al modelo.
    """
    omitir: list[str] = field(default_factory=list)
    columna_hablante: dict[str, int] = field(default_factory=dict)
    hablantes: dict[str, str] = field(default_factory=dict)
    variables: dict[str, str] = field(default_factory=dict)
    otros_valores: dict[str, list[tuple[str, str]]] = field(default_factory=dict)

    @classmethod
    def desde_dict(cls, datos: dict | None) -> "AjustesTablas":
        datos = datos or {}
        otros: dict[str, list[tuple[str, str]]] = {}
        for codigo, valores in (datos.get("otros_valores") or {}).items():
            valores = [valores] if isinstance(valores, dict) else valores
            otros[str(codigo)] = [(str(v["en"]), str(v["es"])) for v in valores if v.get("en") and v.get("es")]
        return cls(omitir=list(datos.get("omitir") or []),
                   columna_hablante={str(k): int(v) for k, v in (datos.get("columna_hablante") or {}).items()},
                   hablantes={str(k): str(v or "") for k, v in (datos.get("hablantes") or {}).items()},
                   variables={str(k): str(v) for k, v in (datos.get("variables") or {}).items()},
                   otros_valores=otros)

    @classmethod
    def del_juego(cls, juego: str | None) -> "AjustesTablas":
        from ..config import ajustes_juego
        return cls.desde_dict(ajustes_juego(juego).get("tablas_unity") if juego else None)

    def se_omite(self, nombre: str) -> bool:
        return any(fnmatch.fnmatchcase(nombre, p) for p in self.omitir)

    def columna_de(self, nombre: str) -> int | None:
        return next((c for p, c in self.columna_hablante.items() if fnmatch.fnmatchcase(nombre, p)), None)

    def sustituir(self, texto: str, variante: int | None = None) -> str:
        """Pone el valor de cada variable; con ``variante`` = k, el k-ésimo de ``otros_valores`` si lo hay."""
        for codigo in {**self.variables, **self.otros_valores}:
            otros = self.otros_valores.get(codigo, [])
            if variante is not None and variante < len(otros):
                texto = texto.replace(codigo, otros[variante][0])
            elif codigo in self.variables:
                texto = texto.replace(codigo, self.variables[codigo])
        return texto

    @property
    def n_variantes(self) -> int:
        return max((len(v) for v in self.otros_valores.values()), default=0)

    def tiene_otros_valores(self, texto: str) -> bool:
        return any(codigo in texto for codigo in self.otros_valores)


# --------------------------------------------------------------------------- lectura de tablas
@dataclass
class TablaTexto:
    nombre: str
    cabecera: list[str]
    filas: list[list[str]]
    col_en: int
    entradas: list[tuple[str, str | None]] = field(default_factory=list)  # (inglés, sexo de quien habla)
    oyentes: dict[str, str | None] = field(default_factory=dict)          # inglés -> sexo de quien escucha
    hablantes: dict[str, str | None] = field(default_factory=dict)        # inglés -> columna de quién habla
    crudas: dict[str, set[str]] = field(default_factory=dict)  # inglés -> texto con códigos con otros valores

    @property
    def es_dialogo(self) -> bool:
        """Frases largas en orden de historia: aquí sí ayuda la conversación previa."""
        palabras = [len(t.split()) for t, _ in self.entradas]
        return bool(palabras) and statistics.median(palabras) >= 8


def _texto_visible_ingles(texto: str) -> bool:
    return bool(texto.strip()) and not _CJK.search(texto) and bool(re.search(r"[A-Za-z]{2}", texto)) \
        and tiene_texto_visible(texto)


def leer_tabla(nombre: str, contenido: str, ajustes: AjustesTablas | None = None) -> TablaTexto | None:
    """Una tabla con columna inglesa, o None si el texto no lo es."""
    ajustes = ajustes or AjustesTablas()
    col_hablante = ajustes.columna_de(nombre)
    if "\x00" in contenido[:2000]:
        return None
    # fin de línea de Windows -> "\n"; un "\r" suelto dentro de una celda rompería el lector de CSV
    contenido = contenido.replace("\r\n", "\n").replace("\r", "")
    primera = contenido.split("\n", 1)[0]
    tab = primera.count("\t") >= max(1, primera.count(","))
    try:
        if tab:  # en TSV las comillas son texto ("Hm?"), no delimitan celdas
            filas = list(csv.reader(io.StringIO(contenido), delimiter="\t", quoting=csv.QUOTE_NONE))
        else:
            filas = list(csv.reader(io.StringIO(contenido)))
    except csv.Error:
        return None
    if len(filas) < 2:
        return None
    cab = [c.strip().lower() for c in filas[0]]
    col = next((i for i, c in enumerate(cab) if c in COLUMNAS_INGLES or c.endswith("_en")), None)
    if col is None:
        return None
    tabla = TablaTexto(nombre, filas[0], filas[1:], col)
    vistos: dict[str, int] = {}
    for fila in tabla.filas:
        if len(fila) <= col:
            continue
        crudo = fila[col].replace("\\n", "\n")  # el juego convierte el "\n" escrito en salto
        texto = ajustes.sustituir(crudo)
        if not _texto_visible_ingles(texto):
            continue
        if ajustes.tiene_otros_valores(crudo):  # la frase y cada trozo, con sus códigos
            partes = [crudo] + ([p.strip() for p in _PAUSA.split(crudo)] if _PAUSA.search(crudo) else [])
            for parte in partes:
                if ajustes.tiene_otros_valores(parte):
                    tabla.crudas.setdefault(ajustes.sustituir(parte), set()).add(parte)
        celdas = {cab[i]: fila[i] for i in range(min(len(cab), len(fila)))}
        genero = genero_de_quien_habla(celdas)
        oyente = genero_de_quien_escucha(celdas)
        quien = fila[col_hablante].strip() or None if col_hablante is not None and col_hablante < len(fila) else None
        # Una pausa del juego en mitad de la frase ("...culture,{wc} so she..."): el juego enseña cada
        # trozo por separado y XUnity los ve sueltos, así que también se traduce cada trozo
        trozos = [p.strip() for p in _PAUSA.split(texto)] if _PAUSA.search(texto) else []
        for frase in [texto] + [p for p in trozos if _texto_visible_ingles(p)]:
            if frase in vistos:  # la misma frase dicha por/a personas de distinto sexo: sin pista
                i = vistos[frase]
                if tabla.entradas[i][1] != genero:
                    tabla.entradas[i] = (frase, None)
                if tabla.oyentes.get(frase) != oyente:
                    tabla.oyentes[frase] = None
                if tabla.hablantes.get(frase) != quien:
                    tabla.hablantes[frase] = None
                continue
            vistos[frase] = len(tabla.entradas)
            tabla.entradas.append((frase, genero))
            tabla.oyentes[frase] = oyente
            tabla.hablantes[frase] = quien
    return tabla if tabla.entradas else None


def _archivos_de_datos(ruta_juego: Path) -> list[Path]:
    from ..unity_dialogos import _archivos_de_datos as archivos
    return archivos(ruta_juego)


def extraer_tablas(ruta_juego: Path, ajustes: AjustesTablas | None = None) -> list[TablaTexto]:
    """Todas las tablas de texto con columna inglesa que hay en los archivos del juego (menos las omitidas)."""
    ajustes = ajustes or AjustesTablas()
    try:
        import UnityPy
    except ImportError:
        log.info("UnityPy no está instalado: no se pueden leer las tablas de texto del juego.")
        return []
    tablas: list[TablaTexto] = []
    for ruta in _archivos_de_datos(ruta_juego):
        try:
            env = UnityPy.load(str(ruta))
        except Exception as e:
            log.debug("No se pudo abrir %s: %s", ruta.name, e)
            continue
        for obj in env.objects:
            if obj.type.name != "TextAsset":
                continue
            try:
                datos = obj.read()
                script = datos.m_Script
                if isinstance(script, bytes):
                    script = script.decode("utf-8")
                else:  # UnityPy da str con sustitutos si no era UTF-8
                    script.encode("utf-8")
            except Exception:
                continue
            nombre = getattr(datos, "m_Name", "") or ""
            if ajustes.se_omite(nombre):
                log.info("Tabla de texto '%s' omitida (ajustes del perfil).", nombre)
                continue
            tabla = leer_tabla(nombre, script, ajustes)
            if tabla is not None:
                log.info("Tabla de texto '%s' (%s): %d frases en inglés.", tabla.nombre, ruta.name,
                         len(tabla.entradas))
                tablas.append(tabla)
    return tablas


# --------------------------------------------------------------------------- traducción
def _sin_espacios(texto: str) -> str:
    return re.sub(r"\s+", " ", texto).strip().lower()


def elegir(original: str, anterior: str | None, nueva: str | None) -> str | None:
    """La traducción que se queda: la nueva, salvo que falle, vuelva al inglés o sea peor que la anterior."""
    if not nueva:
        return anterior
    if anterior is None:
        return nueva
    if _sin_espacios(nueva) == _sin_espacios(original) != _sin_espacios(anterior):
        return anterior  # la IA devolvió el inglés y ya había traducción
    if gravedad(evaluar_traduccion(original, nueva)) > gravedad(evaluar_traduccion(original, anterior)):
        return anterior
    return nueva


# Detrás de esto, el nombre empieza frase y va con mayúscula ("¡La chica…", "*Zas*~ La chica…", "(La chica…").
_ABRE_FRASE = "¡¿(«\"“'‘ \t"
_CIERRA_FRASE = ".!?…~*\n"


def _con_mayuscula_si_empieza(traduccion: str, pos: int, valor: str) -> str:
    previo = traduccion[:pos].rstrip(" \t")
    if previo.endswith("\n"):
        return valor[:1].upper() + valor[1:]
    previo = previo.rstrip(_ABRE_FRASE)
    if not previo or previo[-1] in _CIERRA_FRASE:
        return valor[:1].upper() + valor[1:]
    return valor


def traducir_variante(crudo: str, traduccion: str, ajustes: AjustesTablas, variante: int) -> str | None:
    """La traducción de ``crudo`` con los otros valores (variante k) a partir de la hecha con los principales.

    Cambia en la traducción el valor principal ("Lily") por el otro en español ("la chica extraña"), con
    mayúscula si empieza frase. None si no es seguro: el nombre no sale tantas veces como en el inglés, o dos
    códigos con el mismo valor principal piden cosas distintas."""
    cambios: dict[str, str] = {}
    veces: dict[str, int] = {}
    for codigo, principal in ajustes.variables.items():
        n = crudo.count(codigo)
        if not n:
            continue
        otros = ajustes.otros_valores.get(codigo, [])
        nuevo = otros[variante][1] if variante < len(otros) else principal
        if cambios.setdefault(principal, nuevo) != nuevo:
            return None
        veces[principal] = veces.get(principal, 0) + n
    if not any(principal != nuevo for principal, nuevo in cambios.items()):
        return None
    if any(traduccion.count(principal) != veces[principal] for principal in cambios):
        return None
    patron = re.compile("|".join(re.escape(p) for p in sorted(cambios, key=len, reverse=True)))
    return patron.sub(lambda m: _con_mayuscula_si_empieza(m.string, m.start(), cambios[m.group()]), traduccion)


def variantes_por_valores(tablas: list[TablaTexto], ajustes: AjustesTablas,
                          traducciones: dict[str, str]) -> dict[str, str]:
    """{inglés con otro valor: traducción} de las frases con códigos de ``otros_valores`` ya traducidas."""
    nuevas: dict[str, str] = {}
    for tabla in tablas:
        for frase, crudos in tabla.crudas.items():
            hecha = traducciones.get(frase)
            if not hecha or hecha == frase:
                continue
            for crudo in sorted(crudos):
                for k in range(ajustes.n_variantes):
                    ingles = ajustes.sustituir(crudo, k)
                    if ingles == frase or ingles in nuevas:
                        continue
                    traducida = traducir_variante(crudo, hecha, ajustes, k)
                    if traducida:
                        nuevas[ingles] = traducida
    return nuevas


def _unico_por_genero(ficha) -> dict[str, str]:
    """{género: nombre} cuando en la ficha solo hay un personaje de ese género y es el protagonista
    (p. ej. el único chico): entonces una frase dicha por "un chico" la dice él."""
    if ficha is None or not getattr(ficha, "personajes", None):
        return {}
    prota = ficha.protagonista()
    if prota is None:
        return {}
    del_mismo = [p for p in ficha.personajes if p.genero == prota.genero]
    return {prota.genero: prota.nombre} if len(del_mismo) == 1 else {}


class PistasTablas:
    """Lo que las columnas rusa/ucraniana dicen de cada frase inglesa: sexo de quien habla y de quien escucha.

    Sirve a la auditoría de género (``8_auditar_genero.py``) con la misma interfaz que ``TablaHablantes``
    (``info`` y ``escena``) más ``genero_oyente``. Busca la frase tal cual o normalizada (sin etiquetas ni
    comillas tipográficas), como llega de XUnity. Si una frase sale con pistas distintas, no hay pista."""

    def __init__(self, tablas: list[TablaTexto], ficha=None, ajustes: AjustesTablas | None = None):
        from ..unity_dialogos import _normalizar
        self._normalizar = _normalizar
        self._ficha = ficha
        self._ajustes = ajustes or AjustesTablas()
        self._unico = _unico_por_genero(ficha)
        self._hablante: dict[str, str | None] = {}
        self._oyente: dict[str, str | None] = {}
        self._etiqueta: dict[str, str | None] = {}
        for tabla in tablas:
            for frase, genero in tabla.entradas:
                for destino, valor in ((self._hablante, genero), (self._oyente, tabla.oyentes.get(frase)),
                                       (self._etiqueta, tabla.hablantes.get(frase))):
                    for clave in {frase, _normalizar(frase)}:
                        destino[clave] = valor if destino.get(clave, valor) == valor else None

    def __len__(self) -> int:
        return sum(1 for d in (self._hablante, self._oyente, self._etiqueta) for v in d.values() if v)

    def _buscar(self, tabla: dict[str, str | None], texto: str) -> str | None:
        return tabla[texto] if texto in tabla else tabla.get(self._normalizar(texto))

    def info(self, texto: str) -> InfoLinea | None:
        return info_de_fila(self._buscar(self._etiqueta, texto), self._buscar(self._hablante, texto),
                            self._ajustes, self._ficha, self._unico)

    def escena(self, texto: str) -> tuple:
        return ()   # las tablas no dicen quién más está en la conversación

    def genero_oyente(self, texto: str) -> str | None:
        return self._buscar(self._oyente, texto)


def _info(genero: str | None, unico: dict[str, str]) -> InfoLinea | None:
    if not genero:
        return None
    return InfoLinea(hablante=unico.get(genero), genero=genero)


def info_de_fila(etiqueta: str | None, genero: str | None, ajustes: AjustesTablas, ficha,
                 unico: dict[str, str]) -> InfoLinea | None:
    """Quién dice la frase: el personaje de la columna de hablante (si está en ``ajustes.hablantes``) o, si no,
    la pista rusa/ucraniana. Si la pista de ESTA línea contradice el sexo del personaje (una frase citada, una
    fila mal marcada), gana la pista: ante la duda, no se impone el hablante."""
    nombre = ajustes.hablantes.get(etiqueta or "", "") if etiqueta else ""
    if not nombre:
        return _info(genero, unico)
    p = ficha.buscar(nombre) if ficha is not None and getattr(ficha, "personajes", None) else None
    del_personaje = p.genero if p is not None and p.genero_conocido else None
    if genero and del_personaje and genero != del_personaje:
        return _info(genero, unico)
    return InfoLinea(hablante=nombre, genero=del_personaje or genero)


def pretraducir_tablas(ruta_juego: Path, translator, ruta_txt: Path, *, tablas: list[TablaTexto] | None = None,
                       guardar_cada: int = 50, progreso=None, ajustes: AjustesTablas | None = None) -> dict[str, int]:
    """Traduce las tablas de texto del juego y las escribe en ``ruta_txt`` (formato XUnity).

    - Las frases van en el orden de la tabla (el de la historia), con conversación previa en las de diálogo.
    - Lo que ya hubiera en el archivo (otra traducción automática) se sustituye si la nueva no es peor; lo
      que no está en las tablas (números, nombres que el juego monta) se retraduce igual al final.
    - Se guarda cada ``guardar_cada`` frases: si se corta, la caché y el archivo conservan lo hecho.
    """
    ajustes = ajustes or AjustesTablas()
    tablas = extraer_tablas(ruta_juego, ajustes) if tablas is None else tablas
    anteriores = xunity.leer_traducciones(ruta_txt)
    en_tablas = {t for tabla in tablas for t, _ in tabla.entradas}
    sueltas = [o for o in anteriores if o not in en_tablas and _texto_visible_ingles(o)]
    total = sum(len(t.entradas) for t in tablas) + len(sueltas)
    stats = {"frases": total, "con_pista": 0, "cambian": 0, "se_quedan": 0}
    log.info("📚 %d tablas de texto, %d frases (%d con pista de sexo) + %d sueltas del archivo de XUnity.",
             len(tablas), total - len(sueltas), sum(1 for t in tablas for _, g in t.entradas if g), len(sueltas))
    if progreso is not None:
        progreso.definir_totales(total, len(tablas) + (1 if sueltas else 0))
    nuevas: dict[str, str] = {}

    def _guardar() -> None:
        xunity.fusionar_y_guardar(ruta_txt, xunity.construir_entradas(nuevas.items()))

    def _traducir(texto: str, info: InfoLinea | None) -> None:
        try:
            tr = translator.translate(texto, info=info, lanzar_error=True)
        except Exception as e:
            log.debug("Sin traducir (%s): %s", e, texto[:60])
            tr = None
        anterior = anteriores.get(texto)
        final = elegir(texto, anterior, tr)
        if final is None or final == texto:
            return
        if anterior is not None and final == anterior:
            stats["se_quedan"] += 1
        else:
            stats["cambian"] += 1
        nuevas[texto] = final

    ficha = getattr(getattr(translator, "perfil", None), "personajes", None)
    unico = _unico_por_genero(ficha)
    historial_antes = getattr(translator, "usar_historial", False)
    lotes = [(t.nombre, [(e, g, t.hablantes.get(e)) for e, g in t.entradas], t.es_dialogo) for t in tablas]
    if sueltas:
        lotes.append(("(sueltas de XUnity)", [(o, None, None) for o in sueltas], False))
    try:
        hechas = 0
        for indice, (nombre, entradas, dialogo) in enumerate(lotes, 1):
            translator.usar_historial = historial_antes and dialogo
            if hasattr(translator, "historial"):
                translator.historial.clear()
            if progreso is not None:
                progreso.inicio_archivo(nombre, indice, len(entradas))
            for n, (texto, genero, etiqueta) in enumerate(entradas, 1):
                info = info_de_fila(etiqueta, genero, ajustes, ficha, unico)
                stats["con_pista"] += bool(info and (info.hablante or info.genero))
                _traducir(texto, info)
                hechas += 1
                if progreso is not None:
                    progreso.avance_archivo(n)
                if hechas % guardar_cada == 0:
                    _guardar()
                    log.info("  %d/%d frases (%.1f%%)", hechas, total, hechas * 100 / max(1, total))
            if progreso is not None:
                progreso.fin_archivo()
        if ajustes.otros_valores:
            gemelas = variantes_por_valores(tablas, ajustes, {**anteriores, **nuevas})
            nuevas.update(gemelas)
            stats["otros_valores"] = len(gemelas)
            log.info("🔁 %d frases más con otros valores de las variables (p. ej. antes de elegir nombre).",
                     len(gemelas))
    finally:
        translator.usar_historial = historial_antes
        _guardar()
    log.info("✅ Tablas traducidas: %d frases; %d cambian, %d se quedan como estaban (la nueva no era mejor).",
             total, stats["cambian"], stats["se_quedan"])
    return stats
