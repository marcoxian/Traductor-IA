log = logging.getLogger(__name__)

COLUMNAS_INGLES = {"en", "eng", "english", "en-us", "en_us", "en-gb"}
# código de pausa entre dos trozos de frase ("{wc}" = esperar a que se pulse); "{0}" (un número) no lo es
_PAUSA = re.compile(r"\s*\{[A-Za-z]+\}\s*")
_CJK = re.compile(r"[぀-ヿ㐀-鿿가-힯]")

# --------------------------------------------------------------------------- pista de sexo (ruso / ucraniano)
_RU_ELLA = re.compile(
    r"\bя\b(?:\s+\w+){0,3}?\s+\w{2,}(?:ла|лась)\b"
    r"|\bя\s+(?:\w+\s+)?(?:рада|готова|должна|уверена|довольна|согласна|счастлива|благодарна|права|одна|сама)\b",
    re.IGNORECASE)
_RU_EL = re.compile(
    r"\bя\b(?:\s+\w+){0,3}?\s+\w{2,}(?:[аеиоуыяю]л|лся|ёл|ел)\b"
    r"|\bя\s+(?:\w+\s+)?(?:рад|готов|должен|уверен|доволен|согласен|счастлив|благодарен|прав|один|сам)\b",
    re.IGNORECASE)
_UA_ELLA = re.compile(
    r"\bя\b(?:\s+\w+){0,3}?\s+\w{2,}(?:ла|лася)\b"
    r"|\bя\s+(?:\w+\s+)?(?:рада|готова|повинна|впевнена|задоволена|згодна|щаслива|вдячна|сама)\b",
    re.IGNORECASE)
_UA_EL = re.compile(
    r"\bя\b(?:\s+\w+){0,3}?\s+\w{2,}(?:[аеиоуі]в|вся)\b"
    r"|\bя\s+(?:\w+\s+)?(?:радий|готовий|повинен|впевнений|задоволений|згоден|щасливий|вдячний|сам)\b",
    re.IGNORECASE)
_PISTAS = {"ru": (_RU_ELLA, _RU_EL), "rus": (_RU_ELLA, _RU_EL), "russian": (_RU_ELLA, _RU_EL),
           "ua": (_UA_ELLA, _UA_EL), "uk": (_UA_ELLA, _UA_EL), "ukr": (_UA_ELLA, _UA_EL),
           "ukrainian": (_UA_ELLA, _UA_EL)}


# Lo mismo con "tú" (ты / ти): el sexo de quien ESCUCHA ("ты готов" se le dice a él, "ты готова" a ella).
_RU_TU_ELLA = re.compile(
    r"\bты\b(?:\s+\w+){0,3}?\s+\w{2,}(?:ла|лась)\b"
    r"|\bты\s+(?:\w+\s+)?(?:рада|готова|должна|уверена|довольна|согласна|счастлива|права|одна|сама|"
    r"красива|глупа|умна|влюблена|свободна|больна|голодна|нужна)\b",
    re.IGNORECASE)
_RU_TU_EL = re.compile(
    r"\bты\b(?:\s+\w+){0,3}?\s+\w{2,}(?:[аеиоуыяю]л|лся|ёл|ел)\b"
    r"|\bты\s+(?:\w+\s+)?(?:рад|готов|должен|уверен|доволен|согласен|счастлив|прав|один|сам|"
    r"красив|глуп|умён|умен|влюблён|влюблен|свободен|болен|голоден|нужен)\b",
    re.IGNORECASE)
_UA_TU_ELLA = re.compile(
    r"\bти\b(?:\s+\w+){0,3}?\s+\w{2,}(?:ла|лася)\b"
    r"|\bти\s+(?:\w+\s+)?(?:рада|готова|повинна|впевнена|задоволена|згодна|щаслива|сама|одна)\b",
    re.IGNORECASE)
_UA_TU_EL = re.compile(
    r"\bти\b(?:\s+\w+){0,3}?\s+\w{2,}(?:[аеиоуі]в|вся)\b"
    r"|\bти\s+(?:\w+\s+)?(?:радий|готовий|повинен|впевнений|задоволений|згоден|щасливий|сам|один)\b",
    re.IGNORECASE)
_PISTAS_TU = {"ru": (_RU_TU_ELLA, _RU_TU_EL), "rus": (_RU_TU_ELLA, _RU_TU_EL), "russian": (_RU_TU_ELLA, _RU_TU_EL),
              "ua": (_UA_TU_ELLA, _UA_TU_EL), "uk": (_UA_TU_ELLA, _UA_TU_EL), "ukr": (_UA_TU_ELLA, _UA_TU_EL),
              "ukrainian": (_UA_TU_ELLA, _UA_TU_EL)}


def _genero_en(texto: str, ella: re.Pattern, el: re.Pattern) -> str | None:
    f, m = bool(ella.search(texto)), bool(el.search(texto))
    return "mujer" if f and not m else "hombre" if m and not f else None


def _votar(celdas: dict[str, str], pistas: dict[str, tuple[re.Pattern, re.Pattern]]) -> str | None:
    votos = {_genero_en(t, *pistas[c]) for c, t in celdas.items() if c in pistas and t}
    votos.discard(None)
    return votos.pop() if len(votos) == 1 else None


def genero_de_quien_habla(celdas: dict[str, str]) -> str | None:
    """'hombre'/'mujer' si las traducciones rusa/ucraniana de la fila lo dejan claro (y no se contradicen)."""
    return _votar(celdas, _PISTAS)


def genero_de_quien_escucha(celdas: dict[str, str]) -> str | None:
    """'hombre'/'mujer' de la persona a la que se habla ("ты готов" / "ты готова"), si el ruso/ucraniano lo
    deja claro y no se contradicen."""
    return _votar(celdas, _PISTAS_TU)


# --------------------------------------------------------------------------- lectura de tablas
@dataclass
class TablaTexto:
    nombre: str
    cabecera: list[str]
    filas: list[list[str]]
    col_en: int
    entradas: list[tuple[str, str | None]] = field(default_factory=list)  # (inglés, sexo de quien habla)
    oyentes: dict[str, str | None] = field(default_factory=dict)          # inglés -> sexo de quien escucha

    @property
    def es_dialogo(self) -> bool:
        """Frases largas en orden de historia: aquí sí ayuda la conversación previa."""
        palabras = [len(t.split()) for t, _ in self.entradas]
        return bool(palabras) and statistics.median(palabras) >= 8


def _texto_visible_ingles(texto: str) -> bool:
    return bool(texto.strip()) and not _CJK.search(texto) and bool(re.search(r"[A-Za-z]{2}", texto)) \
        and tiene_texto_visible(texto)


def leer_tabla(nombre: str, contenido: str) -> TablaTexto | None:
    """Una tabla con columna inglesa, o None si el texto no lo es."""
    if "\x00" in contenido[:2000]:
        return None
    # fin de línea de Windows -> "\n"; un "\r" suelto dentro de una celda rompería el lector de CSV
    contenido = contenido.replace("\r\n", "\n").replace("\r", "")
    primera = contenido.split("\n", 1)[0]
    tab = primera.count("\t") >= max(1, primera.count(","))
    try:
        if tab:  # en TSV las comillas son texto ("Hm?"), no delimitan celdas
            filas = list(csv.reader(io.StringIO(contenido), delimiter="\t", quoting=csv.QUOTE_NONE))
        else:
            filas = list(csv.reader(io.StringIO(contenido)))
    except csv.Error:
        return None
    if len(filas) < 2:
        return None
    cab = [c.strip().lower() for c in filas[0]]
    col = next((i for i, c in enumerate(cab) if c in COLUMNAS_INGLES), None)
    if col is None:
        return None
    tabla = TablaTexto(nombre, filas[0], filas[1:], col)
    vistos: dict[str, int] = {}
    for fila in tabla.filas:
        if len(fila) <= col:
            continue
        texto = fila[col].replace("\\n", "\n")  # el juego convierte el "\n" escrito en salto
        if not _texto_visible_ingles(texto):
            continue
        celdas = {cab[i]: fila[i] for i in range(min(len(cab), len(fila)))}
        genero = genero_de_quien_habla(celdas)
        oyente = genero_de_quien_escucha(celdas)
        # Una pausa del juego en mitad de la frase ("...culture,{wc} so she..."): el juego enseña cada
        # trozo por separado y XUnity los ve sueltos, así que también se traduce cada trozo
        trozos = [p.strip() for p in _PAUSA.split(texto)] if _PAUSA.search(texto) else []
        for frase in [texto] + [p for p in trozos if _texto_visible_ingles(p)]:
            if frase in vistos:  # la misma frase dicha por/a personas de distinto sexo: sin pista
                i = vistos[frase]
                if tabla.entradas[i][1] != genero:
                    tabla.entradas[i] = (frase, None)
                if tabla.oyentes.get(frase) != oyente:
                    tabla.oyentes[frase] = None
                continue
            vistos[frase] = len(tabla.entradas)
            tabla.entradas.append((frase, genero))
            tabla.oyentes[frase] = oyente
    return tabla if tabla.entradas else None


def _archivos_de_datos(ruta_juego: Path) -> list[Path]:
    from ..unity_dialogos import _archivos_de_datos as archivos
    return archivos(ruta_juego)


def extraer_tablas(ruta_juego: Path) -> list[TablaTexto]:
    """Todas las tablas de texto con columna inglesa que hay en los archivos del juego."""
    try:
        import UnityPy
    except ImportError:
        log.info("UnityPy no está instalado: no se pueden leer las tablas de texto del juego.")
        return []
    tablas: list[TablaTexto] = []
    for ruta in _archivos_de_datos(ruta_juego):
        try:
            env = UnityPy.load(str(ruta))
        except Exception as e:
            log.debug("No se pudo abrir %s: %s", ruta.name, e)
            continue
        for obj in env.objects:
            if obj.type.name != "TextAsset":
                continue
            try:
                datos = obj.read()
                script = datos.m_Script
                if isinstance(script, bytes):
                    script = script.decode("utf-8")
                else:  # UnityPy da str con sustitutos si no era UTF-8
                    script.encode("utf-8")
            except Exception:
                continue
            tabla = leer_tabla(getattr(datos, "m_Name", "") or "", script)
            if tabla is not None:
                log.info("Tabla de texto '%s' (%s): %d frases en inglés.", tabla.nombre, ruta.name,
                         len(tabla.entradas))
                tablas.append(tabla)
    return tablas


# --------------------------------------------------------------------------- traducción
def _sin_espacios(texto: str) -> str:
    return re.sub(r"\s+", " ", texto).strip().lower()


def elegir(original: str, anterior: str | None, nueva: str | None) -> str | None:
    """La traducción que se queda: la nueva, salvo que falle, vuelva al inglés o sea peor que la anterior."""
    if not nueva:
        return anterior
    if anterior is None:
        return nueva
    if _sin_espacios(nueva) == _sin_espacios(original) != _sin_espacios(anterior):
        return anterior  # la IA devolvió el inglés y ya había traducción
    if gravedad(evaluar_traduccion(original, nueva)) > gravedad(evaluar_traduccion(original, anterior)):
        return anterior
    return nueva


def _unico_por_genero(ficha) -> dict[str, str]:
    """{género: nombre} cuando en la ficha solo hay un personaje de ese género y es el protagonista
    (p. ej. el único chico): entonces una frase dicha por "un chico" la dice él."""
    if ficha is None or not getattr(ficha, "personajes", None):
        return {}
    prota = ficha.protagonista()
    if prota is None:
        return {}
    del_mismo = [p for p in ficha.personajes if p.genero == prota.genero]
    return {prota.genero: prota.nombre} if len(del_mismo) == 1 else {}


class PistasTablas:
    """Lo que las columnas rusa/ucraniana dicen de cada frase inglesa: sexo de quien habla y de quien escucha.

    Sirve a la auditoría de género (``8_auditar_genero.py``) con la misma interfaz que ``TablaHablantes``
    (``info`` y ``escena``) más ``genero_oyente``. Busca la frase tal cual o normalizada (sin etiquetas ni
    comillas tipográficas), como llega de XUnity. Si una frase sale con pistas distintas, no hay pista."""

    def __init__(self, tablas: list[TablaTexto], ficha=None):
        from ..unity_dialogos import _normalizar
        self._normalizar = _normalizar
        self._unico = _unico_por_genero(ficha)
        self._hablante: dict[str, str | None] = {}
        self._oyente: dict[str, str | None] = {}
        for tabla in tablas:
            for frase, genero in tabla.entradas:
                for destino, valor in ((self._hablante, genero), (self._oyente, tabla.oyentes.get(frase))):
                    for clave in {frase, _normalizar(frase)}:
                        destino[clave] = valor if destino.get(clave, valor) == valor else None

    def __len__(self) -> int:
        return sum(1 for v in self._hablante.values() if v) + sum(1 for v in self._oyente.values() if v)

    def _buscar(self, tabla: dict[str, str | None], texto: str) -> str | None:
        return tabla[texto] if texto in tabla else tabla.get(self._normalizar(texto))

    def info(self, texto: str) -> InfoLinea | None:
        return _info(self._buscar(self._hablante, texto), self._unico)

    def escena(self, texto: str) -> tuple:
        return ()   # las tablas no dicen quién más está en la conversación

    def genero_oyente(self, texto: str) -> str | None:
        return self._buscar(self._oyente, texto)


def _info(genero: str | None, unico: dict[str, str]) -> InfoLinea | None:
    if not genero:
        return None
    return InfoLinea(hablante=unico.get(genero), genero=genero)


def pretraducir_tablas(ruta_juego: Path, translator, ruta_txt: Path, *, tablas: list[TablaTexto] | None = None,
                       guardar_cada: int = 50, progreso=None) -> dict[str, int]:
    """Traduce las tablas de texto del juego y las escribe en ``ruta_txt`` (formato XUnity).

    - Las frases van en el orden de la tabla (el de la historia), con conversación previa en las de diálogo.
    - Lo que ya hubiera en el archivo (otra traducción automática) se sustituye si la nueva no es peor; lo
      que no está en las tablas (números, nombres que el juego monta) se retraduce igual al final.
    - Se guarda cada ``guardar_cada`` frases: si se corta, la caché y el archivo conservan lo hecho.
    """
    tablas = extraer_tablas(ruta_juego) if tablas is None else tablas
    anteriores = xunity.leer_traducciones(ruta_txt)
    en_tablas = {t for tabla in tablas for t, _ in tabla.entradas}
    sueltas = [o for o in anteriores if o not in en_tablas and _texto_visible_ingles(o)]
    total = sum(len(t.entradas) for t in tablas) + len(sueltas)
    stats = {"frases": total, "con_pista": 0, "cambian": 0, "se_quedan": 0}
    log.info("📚 %d tablas de texto, %d frases (%d con pista de sexo) + %d sueltas del archivo de XUnity.",
             len(tablas), total - len(sueltas), sum(1 for t in tablas for _, g in t.entradas if g), len(sueltas))
    if progreso is not None:
        progreso.definir_totales(total, len(tablas) + (1 if sueltas else 0))
    nuevas: dict[str, str] = {}

    def _guardar() -> None:
        xunity.fusionar_y_guardar(ruta_txt, xunity.construir_entradas(nuevas.items()))

    def _traducir(texto: str, info: InfoLinea | None) -> None:
        try:
            tr = translator.translate(texto, info=info, lanzar_error=True)
        except Exception as e:
            log.debug("Sin traducir (%s): %s", e, texto[:60])
            tr = None
        anterior = anteriores.get(texto)
        final = elegir(texto, anterior, tr)
        if final is None or final == texto:
            return
        if anterior is not None and final == anterior:
            stats["se_quedan"] += 1
        else:
            stats["cambian"] += 1
        nuevas[texto] = final

    unico = _unico_por_genero(getattr(getattr(translator, "perfil", None), "personajes", None))
    historial_antes = getattr(translator, "usar_historial", False)
    lotes = [(t.nombre, t.entradas, t.es_dialogo) for t in tablas]
    if sueltas:
        lotes.append(("(sueltas de XUnity)", [(o, None) for o in sueltas], False))
    try:
        hechas = 0
        for indice, (nombre, entradas, dialogo) in enumerate(lotes, 1):
            translator.usar_historial = historial_antes and dialogo
            if hasattr(translator, "historial"):
                translator.historial.clear()
            if progreso is not None:
                progreso.inicio_archivo(nombre, indice, len(entradas))
            for n, (texto, genero) in enumerate(entradas, 1):
                info = _info(genero, unico)
                stats["con_pista"] += bool(genero)
                _traducir(texto, info)
                hechas += 1
                if progreso is not None:
                    progreso.avance_archivo(n)
                if hechas % guardar_cada == 0:
                    _guardar()
                    log.info("  %d/%d frases (%.1f%%)", hechas, total, hechas * 100 / max(1, total))
            if progreso is not None:
                progreso.fin_archivo()
    finally:
        translator.usar_historial = historial_antes
        _guardar()
    log.info("✅ Tablas traducidas: %d frases; %d cambian, %d se quedan como estaban (la nueva no era mejor).",
             total, stats["cambian"], stats["se_quedan"])
    return stats
