"""Tests del formato de archivo de XUnity.AutoTranslator (traductor/xunity.py).

Los valores esperados se verificaron contra TextHelper.Encode / ReadTranslationLineAndDecode
del propio XUnity.AutoTranslator.Plugin.Core.dll (v5.6.2).
"""
import tempfile
import unittest
from pathlib import Path

from traductor import xunity


class TestEscapadoXUnity(unittest.TestCase):
    def test_escapar_como_xunity(self):
        self.assertEqual(xunity.escapar("A=B [pic=2] / // C:\\path\nline2\r end"),
                         "A\\=B [pic\\=2] / \\/\\/ C:\\\\path\\nline2\\r end")
        self.assertEqual(xunity.escapar("///"), "\\/\\//")
        self.assertEqual(xunity.escapar("x/"), "x/")

    def test_linea_con_igual_sin_escapar_es_invalida(self):
        # Esto es lo que escribían antes los scripts: XUnity descarta la línea.
        self.assertIsNone(xunity.leer_linea("Giggle [pic=2]=Risita"))
        self.assertEqual(xunity.leer_linea("Giggle [pic\\=2]=Risita"), ("Giggle [pic=2]", "Risita"))

    def test_comentarios_y_dobles_barras(self):
        self.assertIsNone(xunity.leer_linea("//comentario=x"))
        self.assertIsNone(xunity.leer_linea("a // b=c"))

    def test_ida_y_vuelta(self):
        casos = [("Hola\nmundo", "Hello\nworld"), ("a=b", "c=d"), ("C:\\x", "y\\n"), ("[pic=9] Hi", "[pic=9] Hola")]
        for o, t in casos:
            self.assertEqual(xunity.leer_linea(xunity.formatear_linea(o, t)), (o, t))

    def test_fusionar_conserva_lo_existente(self):
        with tempfile.TemporaryDirectory() as tmp:
            ruta = Path(tmp) / "_AutoGeneratedTranslations.txt"
            xunity.escribir_traducciones(ruta, {"Old=1": "Viejo=1", "Keep": "Mantener"})
            final = xunity.fusionar_y_guardar(ruta, {"New\nline": "Nueva\nlínea", "Keep": "Conservar"})
            self.assertEqual(final["Old=1"], "Viejo=1")
            self.assertEqual(final["Keep"], "Conservar")
            self.assertEqual(xunity.leer_traducciones(ruta), final)
            # Cada entrada ocupa exactamente una línea física
            self.assertEqual(len(ruta.read_text(encoding="utf-8-sig").strip().splitlines()), 3)

    def test_variantes_sin_marcas_pixel_crushers(self):
        v = xunity.variantes_clave("Giggle [pic=2]", "Risita [pic=2]")
        self.assertEqual(v["Giggle [pic=2]"], "Risita [pic=2]")
        self.assertEqual(v["Giggle"], "Risita")
        v = xunity.variantes_clave("Line one\nline two", "Línea uno\nlínea dos")
        self.assertEqual(v["Line one line two"], "Línea uno línea dos")

    def test_construir_entradas_descarta_identicas(self):
        self.assertEqual(xunity.construir_entradas([("Vili", "Vili"), ("Hi", "")]), {})


if __name__ == "__main__":
    unittest.main()

