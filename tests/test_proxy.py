"""Proxy de XUnity: frases a medio escribir, textos solo de cifras y cifras cambiadas en textos cortos."""
from __future__ import annotations

import tempfile
import unittest
from pathlib import Path
from unittest.mock import MagicMock

import ollama_proxy
from ollama_proxy import (DiccionarioJuego, cifras_mal_en_texto_corto, con_angulos, con_llaves,
                          es_solo_cifras, quitar_texto_oculto)


class TestFuncionesProxy(unittest.TestCase):
    def test_frase_a_medio_escribir_con_color_transparente(self):
        self.assertEqual(quitar_texto_oculto("Hola, qu<color=#FFFFFF00>é tal la tarde?</color>"),
                         "Hola, qué tal la tarde?")
        self.assertEqual(quitar_texto_oculto("A<color=#ffffff00>bc</color>"), "Abc")

    def test_frase_a_medio_escribir_con_alfa(self):
        self.assertEqual(quitar_texto_oculto("Buenos d<alpha=#00>ías"), "Buenos días")

    def test_color_visible_no_es_texto_oculto(self):
        self.assertIsNone(quitar_texto_oculto("Mira <color=#ff6d77>eso</color> de ahí"))
        self.assertIsNone(quitar_texto_oculto("Mira <color=#ff6d77ff>eso</color>"))
        self.assertIsNone(quitar_texto_oculto("Texto normal"))

    def test_solo_cifras(self):
        for texto in ("2.0x", "1.5x", "x999", "x1", "1/4", "+300", "(5)", "50%"):
            self.assertTrue(es_solo_cifras(texto), texto)
        for texto in ("Lv2", "Day 3", "x", "Owned:2", "8 Times", ""):
            self.assertFalse(es_solo_cifras(texto), texto)

    def test_cifras_mal_solo_en_textos_cortos(self):
        self.assertTrue(cifras_mal_en_texto_corto("(8 Times)", ["numeros"]))
        self.assertFalse(cifras_mal_en_texto_corto("(8 Times)", []))
        largo = "The old baker sold 12 loaves before the market closed today"
        self.assertFalse(cifras_mal_en_texto_corto(largo, ["numeros"]))

    def test_etiquetas_llaves_y_angulos(self):
        self.assertEqual(con_llaves("Coge <color=#f00><i>eso</i></color>"), "Coge {color=#f00}{i}eso{/i}{/color}")
        self.assertEqual(con_angulos("Coge {color=#f00}{i}eso{/i}{/color}"), "Coge <color=#f00><i>eso</i></color>")
        self.assertEqual(con_llaves("Hola {0} y <wave>"), "Hola {0} y <wave>")


class TestDiccionarioJuego(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.ruta = Path(self.tmp.name) / "_AutoGeneratedTranslations.txt"
        self.ruta.write_text(
            "Where is the red lantern?=¿Dónde está el farol rojo?\n"
            "Grab {color\\=#f00}that{/color} now.=Coge {color\\=#f00}eso{/color} ya.\n"
            "Stock:{0}=Tienes:{0}\n"
            "Plate {0}=Plato {0}\n"
            "Plate List ({0}/4)=Lista de platos ({0}/4)\n"
            "Trade {0} shells for {1} pearls=Cambia {0} conchas por {1} perlas\n",
            encoding="utf-8")

    def test_plantillas_con_numeros(self):
        d = DiccionarioJuego(self.ruta)
        self.assertEqual(d.buscar("Stock:350"), "Tienes:350")
        self.assertEqual(d.buscar("Plate 2"), "Plato 2")
        self.assertEqual(d.buscar("Plate List (1/4)"), "Lista de platos (1/4)")
        self.assertEqual(d.buscar("Trade 3 shells for 12 pearls"), "Cambia 3 conchas por 12 perlas")
        # Solo números en los huecos: "Plate Rack" no es "Plate {0}"
        self.assertIsNone(d.buscar("Plate Rack"))
        self.assertIsNone(d.buscar("Stock:"))

    def tearDown(self):
        self.tmp.cleanup()

    def test_busca_frase_y_variante_con_angulos(self):
        d = DiccionarioJuego(self.ruta)
        self.assertEqual(d.buscar("Where is the red lantern?"), "¿Dónde está el farol rojo?")
        self.assertEqual(d.buscar("Grab <color=#f00>that</color> now."), "Coge <color=#f00>eso</color> ya.")
        self.assertIsNone(d.buscar("Unknown line"))

    def test_sin_archivo(self):
        self.assertIsNone(DiccionarioJuego(None).buscar("Where is the red lantern?"))

    def test_proxy_responde_la_frase_entera_sin_llamar_al_modelo(self):
        traductor = MagicMock()
        servidor = ollama_proxy.iniciar_servidor_proxy(traductor, puerto=0, ruta_traducciones=self.ruta)
        try:
            handler = servidor.RequestHandlerClass
            codigo, texto = handler._traducir_coordinado(
                handler, "Where is the r<color=#FFFFFF00>ed lantern?</color>")
            self.assertEqual((codigo, texto), (200, "¿Dónde está el farol rojo?"))
            self.assertEqual(handler._traducir_coordinado(handler, "2.0x"), (200, "2.0x"))
            traductor.translate.assert_not_called()
        finally:
            servidor.server_close()

    def test_proxy_traduce_la_frase_entera_si_no_esta(self):
        traductor = MagicMock()
        traductor.translate.return_value = "El gato duerme en la silla."
        servidor = ollama_proxy.iniciar_servidor_proxy(traductor, puerto=0, ruta_traducciones=self.ruta)
        try:
            handler = servidor.RequestHandlerClass
            codigo, texto = handler._traducir_coordinado(
                handler, "The cat sl<color=#FFFFFF00>eeps on the chair.</color>")
            self.assertEqual((codigo, texto), (200, "El gato duerme en la silla."))
            traductor.translate.assert_called_once_with("The cat sleeps on the chair.", info=None)
        finally:
            servidor.server_close()

    def test_via_de_cada_respuesta(self):
        traductor = MagicMock()
        traductor.estadisticas = {"traducidas": 0}

        def traducir(texto, info=None):
            traductor.estadisticas["traducidas"] += 1
            return "El gato duerme en la silla."
        traductor.translate.side_effect = traducir
        servidor = ollama_proxy.iniciar_servidor_proxy(traductor, puerto=0, ruta_traducciones=self.ruta)
        try:
            handler = servidor.RequestHandlerClass
            self.assertEqual(handler._resolver("Stock:7"), (200, "Tienes:7", "diccionario:plantilla"))
            self.assertEqual(handler._resolver("Where is the r<color=#FFFFFF00>ed lantern?</color>")[2],
                             "oculto+diccionario:frase")
            self.assertEqual(handler._resolver("x999")[2], "igual")
            self.assertEqual(handler._resolver("The cat sleeps on the chair.")[2], "modelo")
            traductor.translate.side_effect = None
            traductor.translate.return_value = "El gato duerme en la silla."
            self.assertEqual(handler._resolver("The cat sleeps on the chair.")[2], "cache")
        finally:
            servidor.server_close()

    def test_registro_a_archivo(self):
        ruta = Path(self.tmp.name) / "registro" / "dia.jsonl"
        registro = ollama_proxy.RegistroProxy(ruta)
        registro.anotar(via="modelo", texto="Hello there", respuesta="Hola")
        registro.anotar(via="cache", texto="Bye", respuesta="Adiós")
        import json
        lineas = [json.loads(l) for l in ruta.read_text(encoding="utf-8").splitlines()]
        self.assertEqual([l["via"] for l in lineas], ["modelo", "cache"])
        self.assertEqual(lineas[1]["respuesta"], "Adiós")
        ollama_proxy.RegistroProxy(None).anotar(via="x")  # sin ruta no hace nada

    def test_proxy_rechaza_cifras_cambiadas_en_texto_corto(self):
        traductor = MagicMock()
        traductor.translate.return_value = "(Antes de que tú...)"
        servidor = ollama_proxy.iniciar_servidor_proxy(traductor, puerto=0)
        try:
            handler = servidor.RequestHandlerClass
            self.assertEqual(handler._traducir_coordinado(handler, "(8 Times)")[0], 503)
        finally:
            servidor.server_close()


class TestAnalizarRegistro(unittest.TestCase):
    def test_motivo_de_cada_frase_en_directo(self):
        import sys
        sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "herramientas_extra"))
        from analizar_registro_proxy import Buscador
        b = Buscador({"Hello there,\nfriend.": "x", "Gold: 50": "y", "<b>Big</b> dog": "z",
                      "The long road goes on and on": "w"})
        self.assertEqual(b.motivo("Hello there, friend."), ("espacios", "Hello there,\nfriend."))
        self.assertEqual(b.motivo("hello there, friend.")[0], "mayusculas")
        self.assertEqual(b.motivo("Big dog")[0], "etiquetas")
        self.assertEqual(b.motivo("Gold: 75")[0], "cifras")
        self.assertEqual(b.motivo("road goes on")[0], "trozo")
        self.assertEqual(b.motivo("Nothing alike"), ("nueva", None))


if __name__ == "__main__":
    unittest.main()
